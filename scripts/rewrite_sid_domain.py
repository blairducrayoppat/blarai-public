"""Rewrite one machine SID domain to a placeholder domain in every TRACKED file of this repository, in place.

Run:  python scripts/rewrite_sid_domain.py --log docs/reviews/<log>.md            (rewrites; reads the domain from this machine)
      python scripts/rewrite_sid_domain.py --domain a-b-c --log <log>.md          (rewrites a named domain)
      python scripts/rewrite_sid_domain.py --check                                (exit 1 if any tracked file still carries the domain)

What it changes and nothing else: the three sub-authority numbers of one Windows account domain (``a-b-c`` as in
``S-1-5-21-a-b-c-1001``) become the placeholder domain, byte for byte, wherever the digits appear, with or without the
``S-1-5-21-`` prefix. The relative id after the domain is kept, so ``...-1001`` stays the operator's account and
``...-1271`` the spike account. Bytes outside the match are untouched: line endings, byte-order marks, JSON layout,
timestamps and every number that is not the domain stay as they were. Files are taken from ``git ls-files`` only:
untracked files belong to other sessions and are not touched. Files that contain a NUL byte are treated as binary and
skipped (reported in the log).

The placeholder is the shape-valid domain the containment-evidence bundle already uses
(``docs/research/containment-evidence-2026-10-05/CHANGES.md``), so code that validates SID shape keeps working and
every sanitised surface of the repository agrees on one placeholder.

The log (Markdown) records, per changed file, the number of occurrences replaced and the sha256 of the LF-normalised
bytes before and after (the bundle's hash convention), so any fingerprint recorded elsewhere can be re-recorded from
the log without re-deriving it. The domain itself is never written to the log or to this file: this script reads it
from the local machine (.NET ``WindowsIdentity``) unless ``--domain`` names it.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

PLACEHOLDER_DOMAIN = "1000000001-1000000002-1000000003"
DOMAIN_SHAPE = re.compile(r"^\d{1,10}-\d{1,10}-\d{1,10}$")
_LIVE_DOMAIN_CMD = "[System.Security.Principal.WindowsIdentity]::GetCurrent().User.AccountDomainSid.Value"


def repo_root(start: Path) -> Path:
    out = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=start, capture_output=True, text=True, check=True)
    return Path(out.stdout.strip())


def tracked_files(root: Path) -> list[Path]:
    out = subprocess.run(["git", "ls-files", "-z"], cwd=root, capture_output=True, check=True).stdout
    return [root / p.decode("utf-8") for p in out.split(b"\0") if p]


def live_machine_domain() -> str:
    """The account domain of the current Windows identity, as ``a-b-c``. Raises when it cannot be read."""
    for shell in ("pwsh", "powershell"):
        try:
            out = subprocess.run([shell, "-NoProfile", "-Command", _LIVE_DOMAIN_CMD], capture_output=True, text=True, timeout=60, check=False).stdout.strip()
        except (OSError, subprocess.SubprocessError):
            continue
        m = re.fullmatch(r"S-1-5-21-(\d+-\d+-\d+)", out)
        if m:
            return m.group(1)
    raise RuntimeError("the machine's account domain could not be read from .NET WindowsIdentity (pwsh or powershell)")


def lf_sha256(data: bytes) -> str:
    return hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()


def rewrite_bytes(data: bytes, domain: str, placeholder: str = PLACEHOLDER_DOMAIN) -> tuple[bytes, int]:
    """Replace every occurrence of ``domain`` (digits, dashes) with ``placeholder``; return the new bytes and the count."""
    needle, repl = domain.encode("ascii"), placeholder.encode("ascii")
    return data.replace(needle, repl), data.count(needle)


def scan(root: Path, domain: str) -> tuple[list[tuple[Path, int, bytes]], list[Path]]:
    """Tracked text files carrying the domain (path, occurrences, bytes) and tracked binary files carrying it (reported, not rewritten)."""
    carrying: list[tuple[Path, int, bytes]] = []
    binary: list[Path] = []
    needle = domain.encode("ascii")
    for p in tracked_files(root):
        if not p.is_file():
            continue
        data = p.read_bytes()
        n = data.count(needle)
        if not n:
            continue
        if b"\0" in data:
            binary.append(p)
        else:
            carrying.append((p, n, data))
    return carrying, binary


def render_log(root: Path, rows: list[tuple[Path, int, str, str]], binary: list[Path], placeholder: str, head: str) -> str:
    lines = [
        f"# SID-domain rewrite log ({head})",
        "",
        "Generated by `scripts/rewrite_sid_domain.py`. The machine account domain that was replaced is not written here; it is the domain",
        f"`tests/security/test_no_machine_sid_domain_in_tree.py` pins by digest. Placeholder written: `S-1-5-21-{placeholder}` (relative ids kept).",
        "Hashes are sha256 of LF-normalised bytes, the bundle's convention.",
        "",
        f"Files rewritten: {len(rows)}. Occurrences replaced: {sum(r[1] for r in rows)}.",
        "",
        "| File | Occurrences | sha256 before | sha256 after |",
        "|---|---|---|---|",
    ]
    for p, n, before, after in rows:
        lines.append(f"| `{p.relative_to(root).as_posix()}` | {n} | `{before}` | `{after}` |")
    if binary:
        lines += ["", "Binary tracked files carrying the domain, NOT rewritten (rewrite by hand or remove):", ""]
        lines += [f"- `{p.relative_to(root).as_posix()}`" for p in binary]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--domain", help="the account domain to replace, as a-b-c (default: read from this machine)")
    ap.add_argument("--placeholder", default=PLACEHOLDER_DOMAIN, help="the domain to write instead (default: the bundle's)")
    ap.add_argument("--log", type=Path, help="Markdown log to write (required unless --check)")
    ap.add_argument("--check", action="store_true", help="only report; exit 1 if any tracked file carries the domain")
    a = ap.parse_args(argv)
    root = repo_root(Path.cwd())
    try:
        domain = a.domain or live_machine_domain()
    except RuntimeError as e:
        print(f"REFUSED: {e}", file=sys.stderr)
        return 2
    if not DOMAIN_SHAPE.match(domain) or not DOMAIN_SHAPE.match(a.placeholder):
        print("REFUSED: domain and placeholder must be three dash-separated numbers (a-b-c)", file=sys.stderr)
        return 2
    if domain == a.placeholder:
        print("REFUSED: the domain to replace equals the placeholder", file=sys.stderr)
        return 2
    carrying, binary = scan(root, domain)
    if a.check:
        for p, n, _ in carrying:
            print(f"carries the domain ({n}): {p.relative_to(root).as_posix()}")
        for p in binary:
            print(f"carries the domain (binary): {p.relative_to(root).as_posix()}")
        print(f"{len(carrying) + len(binary)} tracked file(s) carry the domain")
        return 1 if (carrying or binary) else 0
    if a.log is None:
        print("REFUSED: --log is required when rewriting", file=sys.stderr)
        return 2
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=root, capture_output=True, text=True, check=True).stdout.strip()
    rows: list[tuple[Path, int, str, str]] = []
    for p, n, data in carrying:
        new, count = rewrite_bytes(data, domain, a.placeholder)
        p.write_bytes(new)
        rows.append((p, count, lf_sha256(data), lf_sha256(new)))
        print(f"rewritten ({count}): {p.relative_to(root).as_posix()}")
    a.log.parent.mkdir(parents=True, exist_ok=True)
    a.log.write_bytes(render_log(root, rows, binary, a.placeholder, head).encode("utf-8"))
    print(f"{len(rows)} file(s) rewritten, {sum(r[1] for r in rows)} occurrence(s); log: {a.log}")
    return 1 if binary else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
