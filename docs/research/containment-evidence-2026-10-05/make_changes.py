"""Generate CHANGES.md and confined-model-spike/as-run/MANIFEST.sha256 from the bundle's own contents.

Run:  python make_changes.py          (rewrites both files next to this script)
      python make_changes.py --check  (exit 1 if either file differs from what the bundle's contents produce)

Everything is computed on LF-NORMALISED bytes (CRLF -> LF before hashing, counting or diffing), so the output does not depend on
the checkout's line-ending setting. The bundle test regenerates both files, also on a copy converted to CRLF, and compares them with
the committed files. The generator reads only the bundle: the raw sources (which carry real identifiers) are not needed.
"""

from __future__ import annotations

import difflib
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
USER_PH, MACH_PH = "_OPERATOR_", "_MACHINE_"
PH_DOMAINS = ("1000000001-1000000002-1000000003", "1000000004-1000000005-1000000006")
MARKER = "...[truncated to 100 chars]"
META = {"README.md", "CHANGES.md", "make_changes.py"}
AS_RUN = "confined-model-spike/as-run"
HARDENED = "confined-model-spike/post-run-hardened"
ARM1 = "arm1-permit/scripts"
ARM2 = "arm2-hold/scripts"
ARM3 = "arm3-persist/scripts"
MANIFEST = f"{AS_RUN}/MANIFEST.sha256"

MANIFEST_HEADER = """# SHA-256 of the as-run scripts, computed on LF-normalised bytes (CRLF converted to LF before hashing), so the value does not depend on the
# checkout's line-ending setting. This manifest proves the files are UNCHANGED SINCE THIS MANIFEST WAS GENERATED. It does not prove
# provenance: provenance is the first bundle commit 9adcafc4 (16:36 on 2026-10-05, which held these scripts before the hardening) and
# the research-data file times quoted in CHANGES.md. Generated by make_changes.py; do not edit by hand.
"""

HEADER = f"""# Bundle CHANGES (generated by make_changes.py; do not edit by hand)

## Scripts were changed AFTER the runs

The results in this bundle (`confined-model-spike/runs/`, `wfp-spike/result-*.json`) were produced between 15:57 and 16:03 on
2026-10-05. The confined-model scripts were revised afterwards (link-safe cleanup, a strict reader for files the restricted
account writes, private temp files, a password self-check; about 16:44 to 16:50). Two sets are therefore bundled:

- `{AS_RUN}/`: the versions as they stood after the runs and before that hardening. The results come from THESE (see the
  limits below). Their SHA-256 (of LF-normalised bytes) are recorded in `{MANIFEST}` and checked by the test. The manifest proves
  they are unchanged since it was generated; it does not prove provenance (next paragraph).
- `{HARDENED}/`: the current versions. The table below gives the line changes between the two sets.
- `{ARM1}/`: the scripts as changed for arm 1 (the permit filter's role; the account as loopback client), beside that
  arm's results in `arm1-permit/runs/`. The table gives their line changes against the hardened set.
- `{ARM2}/`: the scripts as changed for arm 2 (the long hold), beside that arm's results in `arm2-hold/runs/` (result JSON, the per-sample
  line files and the self-test results; the raw filter exports are not bundled). The table gives their line changes against the arm 1 set.
- `{ARM3}/`: the arm 3 scripts (a persistent filter set, a restart, fail-closed on absence), beside `arm3-persist/DESIGN.md` (written before
  them) and that arm's results in `arm3-persist/runs/`. Files that exist in the arm 2 folder are compared with it; the rest are new.

Provenance and limits of the as-run set: it was recovered from the first bundle commit `9adcafc4` (committed 16:36, after the
runs and before the hardening). The unsanitised originals were overwritten by the hardening: in the research-data folder the
originals of `spike-lib.ps1`, `spike-cleanup.ps1` and the README now carry a 16:50 file time, `spike-provision.ps1` 16:45,
`spike-wfp.ps1` 16:44 and `spike-verify-cleanup.ps1` 16:44, while the runs were 15:57 to 16:03 and the cleanup about 16:25. So the
as-run files here are that commit's copies with the fabricated test SIDs restored from the matching lines of the later versions.
`spike-run-test.ps1` was last modified at 15:59:07: Test A run 1 (15:57:30) ran an EARLIER version (before the inner-exception
fix to the access-check classifier) that no longer exists; Test A run 2 (15:59:14) and Test B (16:00 to 16:02) ran the bundled
version. How the fixed run script reached the task's folder after provisioning is not recorded (inferred from the run outputs).
For the other scripts there is no timestamp evidence of edits between provisioning (15:56) and the first bundle commit.

## Sanitising and line endings

- User name -> `{USER_PH}`; machine name -> `{MACH_PH}` (case-insensitive, everywhere including paths).
- The two real machine SID domains -> `S-1-5-21-1000000001-1000000002-1000000003` and `S-1-5-21-1000000004-1000000005-1000000006`
  (a valid account-domain shape, because the scripts reject any other shape); the relative id after the domain is unchanged.
- Fabricated test SIDs inside the scripts (for example `S-1-5-21-1111111111-2222222222-3333333333-1001`) are NOT touched.
- JSON files are re-serialised (indent 2, UTF-8 without BOM); model text in `text`/`completion`/`body` is cut to 100 characters
  plus the marker `{MARKER}`. No number, timestamp or verdict is changed. Mojibake in raw strings is left as it was.
- Line endings: the originals were CRLF; every text file here is stored LF (the folder is pinned `eol=lf` in `.gitattributes`, and
  all hashes, counts and diffs use LF-normalised bytes). A UTF-8 BOM is kept where the source had one. Script content is otherwise
  unchanged apart from the replacements above.
- `README.md`, `CHANGES.md` and `make_changes.py` are authored here, not copied.
- The counts below are of the placeholders present in each bundled file; the test recounts them.

"""


def _norm(b: bytes) -> bytes:
    return b.replace(b"\r\n", b"\n")


def _read(p: Path) -> str:
    return _norm(p.read_bytes()).decode("utf-8")


def _files(root: Path) -> dict[str, Path]:
    return {
        p.relative_to(root).as_posix(): p
        for p in sorted(root.rglob("*"))
        if p.is_file() and p.relative_to(root).as_posix() not in META and not p.name.startswith("MANIFEST")
        and "__pycache__" not in p.parts
    }


def _diffstat(a: Path, b: Path) -> str:
    plus = minus = 0
    for line in difflib.unified_diff(_read(a).split("\n"), _read(b).split("\n"), lineterm="", n=0):
        if line.startswith("+") and not line.startswith("+++"):
            plus += 1
        elif line.startswith("-") and not line.startswith("---"):
            minus += 1
    return "identical" if plus == minus == 0 else f"+{plus}/-{minus} lines"


def render_manifest(root: Path = ROOT) -> str:
    rows = []
    for rel, p in _files(root).items():
        if rel.startswith(AS_RUN + "/"):
            rows.append(f"{hashlib.sha256(_norm(p.read_bytes())).hexdigest()}  {rel[len(AS_RUN) + 1:]}")
    return MANIFEST_HEADER + "\n".join(sorted(rows, key=lambda r: r.split("  ")[1])) + "\n"


def render_changes(root: Path = ROOT) -> str:
    lines = [
        "| File | Kind | User-name | Machine-name | SID-domain | Model-text cut | Hardened vs as-run (arm 1 vs hardened, arm 2 vs arm 1, arm 3 vs arm 2) |",
        "|---|---|---|---|---|---|---|",
    ]
    files = _files(root)
    for rel, p in files.items():
        text = _read(p)
        kind = "re-serialised JSON" if p.suffix == ".json" else "text copy"
        diff = ""
        if rel.startswith(HARDENED + "/"):
            twin = files.get(f"{AS_RUN}/{rel[len(HARDENED) + 1:]}")
            diff = _diffstat(twin, p) if twin else "no as-run twin"
        elif rel.startswith(AS_RUN + "/"):
            diff = "as-run"
        elif rel.startswith(ARM1 + "/"):
            twin = files.get(f"{HARDENED}/{rel[len(ARM1) + 1:]}")
            diff = ("arm 1 vs hardened: " + _diffstat(twin, p)) if twin else "arm 1 (new file)"
        elif rel.startswith(ARM2 + "/"):
            twin = files.get(f"{ARM1}/{rel[len(ARM2) + 1:]}")
            diff = ("arm 2 vs arm 1: " + _diffstat(twin, p)) if twin else "arm 2 (new file)"
        elif rel.startswith(ARM3 + "/"):
            twin = files.get(f"{ARM2}/{rel[len(ARM3) + 1:]}")
            diff = ("arm 3 vs arm 2: " + _diffstat(twin, p)) if twin else "arm 3 (new file)"
        lines.append(
            f"| `{rel}` | {kind} | {text.count(USER_PH)} | {text.count(MACH_PH)} | "
            f"{sum(text.count(d) for d in PH_DOMAINS)} | {text.count(MARKER)} | {diff or '-'} |"
        )
    return HEADER + "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    changes, manifest = ROOT / "CHANGES.md", ROOT / MANIFEST
    want = {changes: render_changes(), manifest: render_manifest()}
    if "--check" in argv:
        bad = [str(p.relative_to(ROOT)) for p, t in want.items() if not p.exists() or _read(p) != t]
        print("stale: " + ", ".join(bad) if bad else "up to date")
        return 1 if bad else 0
    for p, t in want.items():
        p.write_bytes(t.encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
