#requires -Version 7.0
<#
.SYNOPSIS
  Builds ncoprobe.exe from NcoProbe.cs with the .NET Framework C# compiler already on this machine.

.DESCRIPTION
  Reads NcoProbe.cs once, hashes those bytes, writes them as a snapshot into the build output folder, generates BuildInfo.cs
  there (the embedded source sha256), and compiles the snapshot with
  C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe /platform:x64 /optimize+ /target:exe (no NuGet, no SDK install).
  The snapshot is hashed again after the build: a source that changed under the compiler fails the build.

  The embedded source sha256 is the sha256 of NcoProbe.cs with each CRLF normalised to LF, the convention the case-4
  driver uses for text files, so a checkout's line endings do not change it. The raw-bytes hash is printed beside it.

  -Toggle builds the guard-toggle exe (/define:NCOPROBE_TOGGLE) into its own folder. That exe exists only for
  the tests (`selftest-process`, run by run-probe-selftest.ps1): it can switch a guard off by environment variable and contains no engine-open call. The shipped exe
  never contains that code.

  The build directory must not be inside a git tree. Output layout:
    <BuildDir>\shipped\ncoprobe.exe, NcoProbe.cs (snapshot), BuildInfo.cs, build-record-shipped.json
    <BuildDir>\toggle\ncoprobe.exe,  NcoProbe.cs (snapshot), BuildInfo.cs, build-record-toggle.json
  Output: one JSON object on stdout (the build record); compiler output goes to the host stream.

  Nothing here touches the WFP engine, an account, a task, the registry or the network.
#>
[CmdletBinding()]
param(
    [string]$BuildDir,
    [switch]$Toggle,
    [string]$Csc = 'C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe'
)
$ErrorActionPreference = 'Stop'

function Get-Sha256Hex([byte[]]$Bytes) { [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData($Bytes)).ToLowerInvariant() }

function Get-LfNormalisedBytes([byte[]]$Bytes) {
    # Each CR LF pair becomes LF; a lone CR is kept.
    $out = [System.Collections.Generic.List[byte]]::new($Bytes.Length)
    for ($i = 0; $i -lt $Bytes.Length; $i++) {
        if ($Bytes[$i] -eq 13 -and ($i + 1) -lt $Bytes.Length -and $Bytes[$i + 1] -eq 10) { continue }
        $out.Add($Bytes[$i])
    }
    return , $out.ToArray()
}

function Find-GitRoot([string]$Path) {
    # The nearest folder at or above $Path that holds a .git file or folder; $null when there is none.
    $p = [IO.Path]::GetFullPath($Path)
    while ($p) {
        if (Test-Path -LiteralPath (Join-Path $p '.git')) { return $p }
        $parent = Split-Path -Parent $p
        if (-not $parent -or $parent -eq $p) { break }
        $p = $parent
    }
    return $null
}

if (-not $BuildDir) {
    if (-not $env:USERPROFILE) { throw 'USERPROFILE is not set: pass -BuildDir' }
    $BuildDir = Join-Path $env:USERPROFILE 'rust-bootstrap\ncoprobe-build'
}
$bd = [IO.Path]::GetFullPath($BuildDir)
$gitRoot = Find-GitRoot $bd
if ($gitRoot) { throw "build dir $bd is inside a git tree ($gitRoot)" }

$here = $PSScriptRoot
$src = Join-Path $here 'NcoProbe.cs'
if (-not (Test-Path -LiteralPath $src -PathType Leaf)) { throw "NcoProbe.cs not found beside the build script: $src" }
if (-not (Test-Path -LiteralPath $Csc -PathType Leaf)) { throw "compiler not found: $Csc" }
$srcFull = [IO.Path]::GetFullPath($src)
if ($bd.TrimEnd('\') -eq ([IO.Path]::GetFullPath($here)).TrimEnd('\')) { throw 'the build dir must not be the source folder' }

$flavour = if ($Toggle) { 'toggle' } else { 'shipped' }
$out = Join-Path $bd $flavour
New-Item -ItemType Directory -Force -Path $out | Out-Null

# Read once; everything below works from these bytes.
$srcBytes = [IO.File]::ReadAllBytes($srcFull)
try { $null = [Text.UTF8Encoding]::new($false, $true).GetString($srcBytes) } catch { throw 'NcoProbe.cs is not valid UTF-8' }
$csRaw = Get-Sha256Hex $srcBytes
$csLf = Get-Sha256Hex (Get-LfNormalisedBytes $srcBytes)

$snap = Join-Path $out 'NcoProbe.cs'
[IO.File]::WriteAllBytes($snap, $srcBytes)
$bi = Join-Path $out 'BuildInfo.cs'
$biText = "// Generated by build-probe.ps1 from the NcoProbe.cs snapshot beside it. Do not edit.`n" +
          "namespace NcoProbe`n{`n    internal static class BuildInfo`n    {`n" +
          "        internal const string SourceSha256 = `"$csLf`";`n    }`n}`n"
[IO.File]::WriteAllText($bi, $biText, [Text.UTF8Encoding]::new($false))

$exe = Join-Path $out 'ncoprobe.exe'
if (Test-Path -LiteralPath $exe) { Remove-Item -LiteralPath $exe -Force }
$cscArgs = @('/nologo', '/noconfig', '/platform:x64', '/optimize+', '/target:exe', '/warn:4', '/warnaserror+', '/utf8output',
             '/r:System.dll', '/r:System.Core.dll', "/out:$exe")
if ($Toggle) { $cscArgs += '/define:NCOPROBE_TOGGLE' }
$cscArgs += @($snap, $bi)
$compilerOutput = & $Csc @cscArgs 2>&1
$cscExit = $LASTEXITCODE
$compilerOutput | ForEach-Object { Write-Host $_ }
if ($cscExit -ne 0) { throw "csc failed with exit code $cscExit" }
if (-not (Test-Path -LiteralPath $exe -PathType Leaf)) { throw "built exe not found: $exe" }

# The snapshot must not have changed while the compiler read it.
if ((Get-Sha256Hex ([IO.File]::ReadAllBytes($snap))) -ne $csRaw) { throw 'the source snapshot changed during the build' }

$record = [ordered]@{
    exe                  = $exe
    exe_sha256           = Get-Sha256Hex ([IO.File]::ReadAllBytes($exe))
    cs_sha256            = $csLf
    cs_sha256_convention = 'sha256 of NcoProbe.cs with each CRLF normalised to LF (embedded as BuildInfo.SourceSha256)'
    cs_sha256_raw        = $csRaw
    source               = $srcFull
    source_snapshot      = $snap
    buildinfo            = $bi
    buildinfo_sha256     = Get-Sha256Hex ([IO.File]::ReadAllBytes($bi))
    toggle_build         = [bool]$Toggle
    csc                  = $Csc
    csc_args             = @($cscArgs | ForEach-Object { if ($_ -like '/out:*') { '/out:<exe>' } elseif ($_ -eq $snap) { '<snapshot>' } elseif ($_ -eq $bi) { '<buildinfo>' } else { $_ } })
    built_utc            = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
}
$recordPath = Join-Path $out ("build-record-{0}.json" -f $flavour)
[IO.File]::WriteAllText($recordPath, ($record | ConvertTo-Json -Depth 4), [Text.UTF8Encoding]::new($false))
$record | ConvertTo-Json -Compress -Depth 4
