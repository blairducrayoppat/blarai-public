// NcoProbe.cs: the case-4 probe. Can the account that runs it add and delete one Windows Filtering Platform (WFP) filter
// in the recorded test sublayer S2, under the token it was started with?
//
// Contract
// - Subcommands, each printing one JSON object on stdout:
//     identity                                             token facts; opens no engine
//     selftest                                             every pure check against fake inputs; opens no engine
//     run --cond F|E|S|A --live <proof.json> --out <dir> [--wait]
//                                                          token facts, ONE FwpmFilterAdd0, a read-back, ONE
//                                                          FwpmFilterDeleteByKey0, a read-back; the record is written to
//                                                          <dir>\case4-<cond>-<utc yyyyMMdd-HHmmss>-<pid>.json and printed
//     --version                                            version, own exe sha256, embedded source sha256, toggle flag
//     selftest-process --exe-dir <dir>                     the process-level rows: runs the shipped and toggle exes named
//                                                          by the build records under <dir> as child processes (refusal
//                                                          vectors only; see ProcessTest); opens no engine itself
// - Every refusal of `run` happens before the first engine open, in this order: arguments (2), arming proof (3), the
//   stale SID must be unmapped (4), the output directory must accept a test file (5), the user SID must be readable (6),
//   the principal must match the condition (12: F and E only as nco-probe, S and A never as nco-probe; this one still
//   writes its record).
// - Names are looked up and recorded only for SIDs of the well-known families (Identity.NameMayBeResolved). The user SID
//   and every account SID (S-1-5-21-*, Microsoft account S-1-11-*, Entra ID S-1-12-*) are recorded as SIDs only.
// - A WFP call that throws is recorded with rc null, class `other` and the exception text; the run then exits 11 (or 8
//   when the filter is or may still be present). Exit 8, exit 11 after the engine was opened, and exit 12 end with a STOP
//   line on stderr.
// - Every engine open passes through Engine.Trace first: when NCOPROBE_ENGINE_OPEN_TRACE names a file, one line is
//   appended BEFORE the engine is touched. If that append fails the probe exits 10 and the engine is never touched.
// - `run` reads its own token, looks up account names and SIDs, hashes its own exe, reads the proof file, creates and
//   deletes one test file in the output directory and writes one record file. The probe changes no account, group, task,
//   registry value or service, and makes no network call. The only WFP calls are FwpmEngineOpen0, one FwpmFilterAdd0,
//   one FwpmFilterDeleteByKey0, FwpmFilterGetByKey0 read-backs, FwpmFreeMemory0 and FwpmEngineClose0. The only processes
//   it starts are the two ncoprobe.exe builds, from selftest-process, under its own token.
// - A build with /define:NCOPROBE_TOGGLE (build-probe.ps1 -Toggle) exists only for the guard-toggle tests. It can switch a
//   guard off by environment variable and contains no engine-open call. The shipped build reads no toggle variable (it
//   names them only to set them for a toggle-build child in selftest-process).
// - The embedded source hash (BuildInfo.SourceSha256, generated by build-probe.ps1) is the sha256 of this file with each
//   CRLF normalised to LF.
//
// Exit codes: 0 ran (identity, selftest, selftest-process and --version: ok), 1 selftest or selftest-process failed, 2 usage, 3 not armed, 4 stale SID
// resolves, 5 output directory unwritable (also: the record could not be written at the end), 6 user SID unreadable,
// 7 engine open failed, 8 ran and the filter was (or may have been) left behind, 10 pre-engine fault (trace file unusable, x64 layout
// mismatch; the engine was not touched), 11 internal error or an engine sequence that could not complete, 12 wrong
// principal for the condition (the engine was not touched).
//
// C# 5, .NET Framework 4.x, x64 only. Struct layouts follow the Windows SDK headers fwpmtypes.h and fwptypes.h; the
// GUIDs and constants are the recorded ones in ../SPEC.md and are compared as text by `selftest`.

