    internal static class Json
    {
        internal const int MaxDepth = 32;

        internal static string Write(object value) { StringBuilder sb = new StringBuilder(); WriteValue(sb, value, 0); return sb.ToString(); }

        static void NewLine(StringBuilder sb, int depth) { sb.Append('\n'); sb.Append(' ', depth * 2); }

        static void WriteValue(StringBuilder sb, object v, int depth)
        {
            if (v == null) { sb.Append("null"); return; }
            if (v is bool) { sb.Append((bool)v ? "true" : "false"); return; }
            string s = v as string;
            if (s != null) { WriteString(sb, s); return; }
            if (v is int) { sb.Append(((int)v).ToString(Util.CI)); return; }
            if (v is long) { sb.Append(((long)v).ToString(Util.CI)); return; }
            if (v is uint) { sb.Append(((uint)v).ToString(Util.CI)); return; }
            if (v is ulong) { sb.Append(((ulong)v).ToString(Util.CI)); return; }
            JNum n = v as JNum;
            if (n != null) { sb.Append(n.Text); return; }
            JObj o = v as JObj;
            if (o != null)
            {
                if (o.Items.Count == 0) { sb.Append("{}"); return; }
                sb.Append('{');
                for (int i = 0; i < o.Items.Count; i++)
                {
                    if (i > 0) sb.Append(',');
                    NewLine(sb, depth + 1);
                    WriteString(sb, o.Items[i].Key);
                    sb.Append(": ");
                    WriteValue(sb, o.Items[i].Value, depth + 1);
                }
                NewLine(sb, depth);
                sb.Append('}');
                return;
            }
            JArr a = v as JArr;
            if (a != null)
            {
                if (a.Items.Count == 0) { sb.Append("[]"); return; }
                sb.Append('[');
                for (int i = 0; i < a.Items.Count; i++)
                {
                    if (i > 0) sb.Append(',');
                    NewLine(sb, depth + 1);
                    WriteValue(sb, a.Items[i], depth + 1);
                }
                NewLine(sb, depth);
                sb.Append(']');
                return;
            }
            throw new ArgumentException("not a JSON value: " + v.GetType().FullName);
        }

        // Everything outside printable ASCII is escaped, so the output survives any console code page.
        internal static void WriteString(StringBuilder sb, string s)
        {
            sb.Append('"');
            foreach (char c in s)
            {
                switch (c)
                {
                    case '"': sb.Append("\\\""); break;
                    case '\\': sb.Append("\\\\"); break;
                    case '\n': sb.Append("\\n"); break;
                    case '\r': sb.Append("\\r"); break;
                    case '\t': sb.Append("\\t"); break;
                    case '\b': sb.Append("\\b"); break;
                    case '\f': sb.Append("\\f"); break;
                    default:
                        if (c < 0x20 || c > 0x7e) sb.Append("\\u").Append(((int)c).ToString("x4", Util.CI));
                        else sb.Append(c);
                        break;
                }
            }
            sb.Append('"');
        }

        // UTF-8 (an optional byte-order mark is skipped); invalid sequences throw ArgumentException.
        internal static string DecodeUtf8Strict(byte[] b)
        {
            int off = (b.Length >= 3 && b[0] == 0xEF && b[1] == 0xBB && b[2] == 0xBF) ? 3 : 0;
            return new UTF8Encoding(false, true).GetString(b, off, b.Length - off);
        }

        // Strict parse. null = success; otherwise the reason. Refused: duplicate keys, nesting deeper than MaxDepth, lone
        // surrogates, raw control characters in strings, leading zeros, trailing commas, and any text after the value.
        internal static string TryParse(string text, out object value)
        {
            value = null;
            if (text == null) return "no text";
            Parser p = new Parser(text);
            try
            {
                p.SkipWs();
                object v = p.ParseValue(0);
                p.SkipWs();
                if (p.Pos != text.Length) return "unexpected text after the JSON value at offset " + p.Pos.ToString(Util.CI);
                value = v;
                return null;
            }
            catch (FormatException e) { return e.Message; }
        }

        sealed class Parser
        {
            readonly string t;
            internal int Pos;
            internal Parser(string text) { t = text; }

            FormatException Err(string m) { return new FormatException(m + " at offset " + Pos.ToString(Util.CI)); }

            internal void SkipWs()
            {
                while (Pos < t.Length && (t[Pos] == ' ' || t[Pos] == '\t' || t[Pos] == '\n' || t[Pos] == '\r')) Pos++;
            }

            bool Lit(string w)
            {
                if (Pos + w.Length <= t.Length && string.CompareOrdinal(t, Pos, w, 0, w.Length) == 0) { Pos += w.Length; return true; }
                return false;
            }

            internal object ParseValue(int depth)
            {
                if (depth > MaxDepth) throw Err("nesting deeper than " + MaxDepth.ToString(Util.CI));
                if (Pos >= t.Length) throw Err("unexpected end of text");
                char c = t[Pos];
                if (c == '{') return ParseObject(depth);
                if (c == '[') return ParseArray(depth);
                if (c == '"') return ParseString();
                if (c == '-' || (c >= '0' && c <= '9')) return ParseNumber();
                if (Lit("true")) return true;
                if (Lit("false")) return false;
                if (Lit("null")) return null;
                throw Err("unexpected character");
            }

            JObj ParseObject(int depth)
            {
                Pos++;
                JObj o = new JObj();
                Dictionary<string, bool> seen = new Dictionary<string, bool>(StringComparer.Ordinal);
                SkipWs();
                if (Pos < t.Length && t[Pos] == '}') { Pos++; return o; }
                while (true)
                {
                    SkipWs();
                    if (Pos >= t.Length || t[Pos] != '"') throw Err("expected a string key");
                    string k = ParseString();
                    if (seen.ContainsKey(k)) throw Err("duplicate key");
                    seen[k] = true;
                    SkipWs();
                    if (Pos >= t.Length || t[Pos] != ':') throw Err("expected ':'");
                    Pos++;
                    SkipWs();
                    o.Add(k, ParseValue(depth + 1));
                    SkipWs();
                    if (Pos < t.Length && t[Pos] == ',') { Pos++; continue; }
                    if (Pos < t.Length && t[Pos] == '}') { Pos++; return o; }
                    throw Err("expected ',' or '}'");
                }
            }

            JArr ParseArray(int depth)
            {
                Pos++;
                JArr a = new JArr();
                SkipWs();
                if (Pos < t.Length && t[Pos] == ']') { Pos++; return a; }
                while (true)
                {
                    SkipWs();
                    a.Add(ParseValue(depth + 1));
                    SkipWs();
                    if (Pos < t.Length && t[Pos] == ',') { Pos++; continue; }
                    if (Pos < t.Length && t[Pos] == ']') { Pos++; return a; }
                    throw Err("expected ',' or ']'");
                }
            }

            static bool IsDigit(char c) { return c >= '0' && c <= '9'; }

            JNum ParseNumber()
            {
                int start = Pos;
                if (t[Pos] == '-') Pos++;
                if (Pos >= t.Length) throw Err("bad number");
                if (t[Pos] == '0') Pos++;
                else if (t[Pos] >= '1' && t[Pos] <= '9') { while (Pos < t.Length && IsDigit(t[Pos])) Pos++; }
                else throw Err("bad number");
                if (Pos < t.Length && t[Pos] == '.')
                {
                    Pos++;
                    int d = Pos;
                    while (Pos < t.Length && IsDigit(t[Pos])) Pos++;
                    if (Pos == d) throw Err("bad fraction");
                }
                if (Pos < t.Length && (t[Pos] == 'e' || t[Pos] == 'E'))
                {
                    Pos++;
                    if (Pos < t.Length && (t[Pos] == '+' || t[Pos] == '-')) Pos++;
                    int d = Pos;
                    while (Pos < t.Length && IsDigit(t[Pos])) Pos++;
                    if (Pos == d) throw Err("bad exponent");
                }
                return new JNum(t.Substring(start, Pos - start));
            }

            internal string ParseString()
            {
                Pos++;
                StringBuilder sb = new StringBuilder();
                while (true)
                {
                    if (Pos >= t.Length) throw Err("unterminated string");
                    char c = t[Pos++];
                    if (c == '"') break;
                    if (c < 0x20) throw Err("control character in string");
                    if (c != '\\') { sb.Append(c); continue; }
                    if (Pos >= t.Length) throw Err("unterminated escape");
                    char e = t[Pos++];
                    switch (e)
                    {
                        case '"': sb.Append('"'); break;
                        case '\\': sb.Append('\\'); break;
                        case '/': sb.Append('/'); break;
                        case 'b': sb.Append('\b'); break;
                        case 'f': sb.Append('\f'); break;
                        case 'n': sb.Append('\n'); break;
                        case 'r': sb.Append('\r'); break;
                        case 't': sb.Append('\t'); break;
                        case 'u':
                            if (Pos + 4 > t.Length) throw Err("short \\u escape");
                            int cp;
                            if (!int.TryParse(t.Substring(Pos, 4), NumberStyles.AllowHexSpecifier, Util.CI, out cp)) throw Err("bad \\u escape");
                            Pos += 4;
                            sb.Append((char)cp);
                            break;
                        default: throw Err("bad escape");
                    }
                }
                string s = sb.ToString();
                for (int i = 0; i < s.Length; i++)
                {
                    if (char.IsHighSurrogate(s[i]))
                    {
                        if (i + 1 < s.Length && char.IsLowSurrogate(s[i + 1])) { i++; continue; }
                        throw Err("lone surrogate in string");
                    }
                    if (char.IsLowSurrogate(s[i])) throw Err("lone surrogate in string");
                }
                return s;
            }
        }
    }

