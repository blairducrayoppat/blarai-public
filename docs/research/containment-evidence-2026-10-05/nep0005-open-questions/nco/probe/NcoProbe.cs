        internal static int Run(string exeDirArg)
        {
            SelfTest.Checks c = new SelfTest.Checks();
            int opensBefore = Engine.Opens;
            Ctx x = new Ctx();
            string exeDir = null;
            try
            {
                exeDir = Path.GetFullPath(exeDirArg);
                Setup(c, x, exeDir);
                SourceBinding(c, x);
                ShippedRows(c, x);
                ToggleRows(c, x);
                SourceScans(c, x);
            }
            catch (Exception e) { c.Check("process.completed", false, "aborted: " + Util.Describe(e)); }
            finally { Cleanup(x); }
            c.Check("cleanup.work_dir_removed", x.Work == null || !Directory.Exists(x.Work), x.Work ?? "no work folder was created");
            c.Check("engine.not_opened_by_this_process", Engine.Opens == opensBefore && Engine.Opens == 0, "engine open count " + Engine.Opens.ToString(Util.CI));

            JObj res = new JObj().Add("subcommand", "selftest-process").Add("probe_version", K.Version).Add("toggle_build", Toggle.IsToggleBuild)
                .Add("exe_dir", exeDir).Add("checks_run", c.RunCount).Add("checks_failed", c.Failed).Add("failures", c.Failures)
                .Add("engine_opens", Engine.Opens).Add("checks", c.All);
            int exit = c.Failed == 0 ? ExitCode.Ok : ExitCode.SelftestFailed;
            res.Add("exit", exit);
            Program.Emit(res);
            return exit;
        }

        static void Setup(SelfTest.Checks c, Ctx x, string exeDir)
        {
            string ps, pt;
            x.Shipped = ReadBuild(exeDir, "shipped", false, out ps);
            x.Toggle = ReadBuild(exeDir, "toggle", true, out pt);
            c.Check("setup.build_records", x.Shipped != null && x.Toggle != null, "shipped: " + (ps ?? "ok") + "; toggle: " + (pt ?? "ok"));
            if (x.Shipped == null || x.Toggle == null) throw new InvalidOperationException("both build records are needed");
            string work = Path.Combine(Path.GetTempPath(), "ncoprobe-process-" + Guid.NewGuid().ToString("N"));
            string git = GitRoot(work);
            c.Check("setup.work_dir_outside_git_tree", git == null, git == null ? work : "inside " + git);
            if (git != null) throw new InvalidOperationException("the temp folder is inside a git tree");
            Directory.CreateDirectory(work);
            x.Work = work;
            x.Proofs = Path.Combine(work, "proofs");
            x.OutOk = Path.Combine(work, "out-ok");
            x.OutDenied = Path.Combine(work, "out-denied");
            x.OutMissing = Path.Combine(work, "out-missing");
            x.OutFile = Path.Combine(work, "out-is-a-file.txt");
            x.Barrier = Path.Combine(work, "no-such-folder", "engine-open.trace");
            x.ToggleTrace = Path.Combine(work, "trace", "engine-open.trace");
            Directory.CreateDirectory(x.Proofs);
            Directory.CreateDirectory(x.OutOk);
            Directory.CreateDirectory(x.OutDenied);
            Directory.CreateDirectory(Path.GetDirectoryName(x.ToggleTrace));
            File.WriteAllText(x.OutFile, "not a folder");
            WindowsIdentity me = WindowsIdentity.GetCurrent();
            x.MySid = me.User.Value;
            FileSystemAccessRule rule = new FileSystemAccessRule(me.User, FileSystemRights.CreateFiles, AccessControlType.Deny);
            DirectorySecurity ds = Directory.GetAccessControl(x.OutDenied);
            ds.AddAccessRule(rule);
            Directory.SetAccessControl(x.OutDenied, ds);
            x.Deny = rule;
        }

        static void Cleanup(Ctx x)
        {
            if (x.Work == null) return;
            try
            {
                if (x.Deny != null && Directory.Exists(x.OutDenied))
                {
                    DirectorySecurity ds = Directory.GetAccessControl(x.OutDenied);
                    ds.RemoveAccessRule(x.Deny);
                    Directory.SetAccessControl(x.OutDenied, ds);
                }
            }
            catch (Exception) { }
            try { Directory.Delete(x.Work, true); } catch (Exception) { }
        }

