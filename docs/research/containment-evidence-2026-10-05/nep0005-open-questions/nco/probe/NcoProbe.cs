        static int RunCmd(Args a)
        {
            DateTime startUtc = DateTime.UtcNow;
            uint pid = Native.GetCurrentProcessId();
            JObj o = Head("run");
            o.Add("cond", a.Cond).Add("clock_start", Util.Clock());
            string path, err;
            string exeSha = Self.ExeSha256(out path, out err);

            // 2. arming
            ProofInfo pi = new ProofInfo();
            string field, detail;
            bool armed = Proof.Arm(a.Live, exeSha, DateTime.UtcNow, pi, out field, out detail);
            o.Add("proof", ProofJson(pi, a.Live));
            if (!armed) return Refuse(o, ExitCode.NotArmed, "not_armed", field, detail, a.Wait);

            // 3. the stale SID must not map
            string subject = Toggle.StaleSubject(K.StaleSid);
            LookupResult lr = Lookup.Sid(subject);
            string staleProblem = Guards.StaleSidProblem(lr.Mapped, lr.Error);
            JObj stale = new JObj().Add("sid", K.StaleSid);
            if (Toggle.IsToggleBuild) stale.Add("looked_up", subject);
            stale.Add("mapped", lr.Mapped).Add("lookup_error", lr.Error).Add("accepted", staleProblem == null);
            o.Add("stale_sid", stale);
            if (staleProblem != null) return Refuse(o, ExitCode.StaleSidResolves, "stale_sid_resolves", "user_sid", staleProblem, a.Wait);

            // 4. output directory
            string outFull;
            string outProblem = Guards.OutDirProblem(a.Out, pid, out outFull);
            o.Add("out_dir", outFull != null ? outFull : a.Out);
            if (outProblem != null) return Refuse(o, ExitCode.OutDirUnwritable, "out_dir_unwritable", "out", outProblem, a.Wait);

            // 5. token facts
            o.Add("clock", Util.Clock());
            string expectedSid;
            string userSid = Identity.AddFacts(o, out expectedSid);
            if (userSid == null) return Refuse(o, ExitCode.UserSidUnreadable, "user_sid_unreadable", "token", "the token's user SID could not be read", a.Wait);

            // pre-engine: layout, the record name, the filter description
            string layout = Guards.LayoutProblem();
            if (layout != null) return Refuse(o, ExitCode.PreEngineFault, "layout_mismatch", "layout", layout, a.Wait);
            string recordName = Record.FileName(a.Cond, startUtc, pid);
            o.Add("stamp_utc", startUtc.ToString("yyyyMMdd-HHmmss", Util.CI)).Add("record_file_name", recordName);
            byte[] sd = Sd.Build(K.StaleSid);
            o.Add("filter", new JObj().Add("key", K.FilterKey.ToString("D")).Add("sublayer", K.SubLayerS2.ToString("D"))
                .Add("provider", K.ProviderKey.ToString("D")).Add("layer", K.LayerAleAuthConnectV4.ToString("D"))
                .Add("user_sid", K.StaleSid).Add("sd_sddl", Sd.ManagedSddl(sd)).Add("display_name", pi.DisplayName)
                .Add("action", Util.Hex32(K.ActionBlock)).Add("weight", "0x" + K.Weight.ToString("X", Util.CI))
                .Add("flags", Util.Hex32(K.FilterFlagPersistent)));

            // 5b. the principal must match the condition (exit 12, before the engine; the record is still written)
            string principalProblem = Guards.PrincipalProblem(a.Cond, userSid, expectedSid);
            o.Add("principal", new JObj().Add("accepted", principalProblem == null).Add("detail", principalProblem));
            if (principalProblem != null)
            {
                JObj prec = new JObj().Add("schema", K.RecordSchema).Add("result", "refused").Add("error", "wrong_principal").Add("field", "principal")
                    .Add("detail", principalProblem).Add("engine_opened", false);
                foreach (KeyValuePair<string, object> kv in o.Items) prec.Add(kv.Key, kv.Value);
                EngineOutcome none = new EngineOutcome();
                string pstop = Outcome.StopLineFor(none, ExitCode.WrongPrincipal);
                Outcome.AddTo(prec, none);
                prec.Add("overall", "wrong_principal").Add("residue", "none_added").Add("exit", ExitCode.WrongPrincipal)
                    .Add("operator_action", pstop).Add("clock_end", Util.Clock());
                return WriteAndFinish(prec, ExitCode.WrongPrincipal, outFull, recordName, a.Wait, pstop);
            }

            // 6-9. the engine
            EngineOutcome eo;
            using (FilterImage img = FilterImage.Build(pi.DisplayName, sd)) { eo = Engine.Drive(img); }
            if (eo.TraceFailed) return Refuse(o, ExitCode.PreEngineFault, "trace_failed", K.TraceVariable, eo.TraceError, a.Wait);
            int exit;
            string overall = Outcome.Overall(eo, out exit);
            string stop = Outcome.StopLineFor(eo, exit);
            JObj rec = new JObj().Add("schema", K.RecordSchema);
            foreach (KeyValuePair<string, object> kv in o.Items) rec.Add(kv.Key, kv.Value);
            Outcome.AddTo(rec, eo);
            rec.Add("overall", overall).Add("residue", Outcome.Residue(eo)).Add("exit", exit).Add("operator_action", stop).Add("clock_end", Util.Clock());

            // 10. the record, written after the engine is closed
            return WriteAndFinish(rec, exit, outFull, recordName, a.Wait, stop);
        }
