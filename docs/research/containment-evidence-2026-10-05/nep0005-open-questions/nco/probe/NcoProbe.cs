    {
        static readonly uint[] KT = {
            0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
            0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
            0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
            0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
            0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
            0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
            0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
            0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2
        };

        static uint Rotr(uint x, int n) { return (x >> n) | (x << (32 - n)); }

        internal static byte[] Hash(byte[] data)
        {
            unchecked
            {
                uint[] h = { 0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19 };
                long bitLen = (long)data.Length * 8;
                int padded = ((data.Length + 9 + 63) / 64) * 64;
                byte[] m = new byte[padded];
                Buffer.BlockCopy(data, 0, m, 0, data.Length);
                m[data.Length] = 0x80;
                for (int i = 0; i < 8; i++) m[padded - 1 - i] = (byte)(bitLen >> (8 * i));
                uint[] w = new uint[64];
                for (int off = 0; off < padded; off += 64)
                {
                    for (int t = 0; t < 16; t++)
                    {
                        int o = off + 4 * t;
                        w[t] = ((uint)m[o] << 24) | ((uint)m[o + 1] << 16) | ((uint)m[o + 2] << 8) | (uint)m[o + 3];
                    }
                    for (int t = 16; t < 64; t++)
                    {
                        uint s0 = Rotr(w[t - 15], 7) ^ Rotr(w[t - 15], 18) ^ (w[t - 15] >> 3);
                        uint s1 = Rotr(w[t - 2], 17) ^ Rotr(w[t - 2], 19) ^ (w[t - 2] >> 10);
                        w[t] = w[t - 16] + s0 + w[t - 7] + s1;
                    }
                    uint a = h[0], b = h[1], c = h[2], d = h[3], e = h[4], f = h[5], g = h[6], hh = h[7];
                    for (int t = 0; t < 64; t++)
                    {
                        uint S1 = Rotr(e, 6) ^ Rotr(e, 11) ^ Rotr(e, 25);
                        uint ch = (e & f) ^ (~e & g);
                        uint t1 = hh + S1 + ch + KT[t] + w[t];
                        uint S0 = Rotr(a, 2) ^ Rotr(a, 13) ^ Rotr(a, 22);
                        uint maj = (a & b) ^ (a & c) ^ (b & c);
                        uint t2 = S0 + maj;
                        hh = g; g = f; f = e; e = d + t1; d = c; c = b; b = a; a = t1 + t2;
                    }
                    h[0] += a; h[1] += b; h[2] += c; h[3] += d; h[4] += e; h[5] += f; h[6] += g; h[7] += hh;
                }
                byte[] r = new byte[32];
                for (int i = 0; i < 8; i++)
                {
                    r[4 * i] = (byte)(h[i] >> 24); r[4 * i + 1] = (byte)(h[i] >> 16); r[4 * i + 2] = (byte)(h[i] >> 8); r[4 * i + 3] = (byte)h[i];
                }
                return r;
            }
        }

        internal static string ToHex(byte[] digest)
        {
            StringBuilder sb = new StringBuilder(digest.Length * 2);
            foreach (byte x in digest) sb.Append(x.ToString("x2", Util.CI));
            return sb.ToString();
        }

        internal static string Hex(byte[] data) { return ToHex(Hash(data)); }
    }

    // The running exe: its path (GetModuleFileNameW) and the sha256 of its bytes, computed once per process.
    internal static class Self
    {
        static bool s_done;
        static string s_path, s_sha, s_error;

        internal static string ExeSha256(out string path, out string error)
        {
            if (!s_done)
            {
                s_done = true;
                try
                {
                    StringBuilder sb = new StringBuilder(32768);
                    uint n = Native.GetModuleFileName(IntPtr.Zero, sb, (uint)sb.Capacity);
                    if (n == 0 || n >= (uint)sb.Capacity) s_error = "GetModuleFileNameW failed with " + Marshal.GetLastWin32Error().ToString(Util.CI);
                    else
                    {
                        s_path = sb.ToString(0, (int)n);
                        s_sha = Sha256.Hex(File.ReadAllBytes(s_path));
                    }
                }
                catch (Exception e) { s_error = Util.Describe(e); s_sha = null; }
            }
            path = s_path;
            error = s_error;
            return s_sha;
        }
    }

    // ---------------------------------------------------------------------------------------------------------------
    // Arguments. Exactly: identity | selftest | --version | selftest-process --exe-dir <dir>
    //                    | run --cond F|E|S|A --live <proof> --out <dir> [--wait].
    // `run` without --live parses; the arming interlock refuses it (exit 3), so the interlock alone owns "no proof".
    // ---------------------------------------------------------------------------------------------------------------
    internal sealed class Args
    {
        internal string Cmd, Cond, Live, Out, ExeDir, Error;
        internal bool Wait;

        internal static bool IsCond(string c) { return c == "F" || c == "E" || c == "S" || c == "A"; }

        internal static Args Parse(string[] a)
        {
            Args r = new Args();
            if (a == null || a.Length == 0) { r.Error = "no subcommand (identity | selftest | run | --version)"; return r; }
            string c = a[0];
            if (c == "identity" || c == "selftest" || c == "--version")
            {
                if (a.Length != 1)
                {
                    bool live = false;
                    foreach (string x in a) { if (x == "--live") live = true; }
                    r.Error = live ? "--live is not accepted by " + c : c + " takes no arguments";
                    return r;
                }
                r.Cmd = c;
                return r;
            }
            if (c == "selftest-process")
            {
                foreach (string x in a) { if (x == "--live") { r.Error = "--live is not accepted by selftest-process"; return r; } }
                if (a.Length != 3 || a[1] != "--exe-dir") { r.Error = "usage: selftest-process --exe-dir <dir>"; return r; }
                if (a[2].Length == 0 || a[2].StartsWith("--", StringComparison.Ordinal)) { r.Error = "missing value for --exe-dir"; return r; }
                r.Cmd = c;
                r.ExeDir = a[2];
                return r;
            }
            if (c != "run") { r.Error = "unknown subcommand"; return r; }
            r.Cmd = "run";
            for (int i = 1; i < a.Length; i++)
            {
                string f = a[i];
                if (f == "--wait")
                {
                    if (r.Wait) { r.Error = "--wait given twice"; return r; }
                    r.Wait = true;
                    continue;
                }
                if (f == "--cond" || f == "--live" || f == "--out")
                {
                    if (i + 1 >= a.Length || a[i + 1].Length == 0 || a[i + 1].StartsWith("--", StringComparison.Ordinal))
                    {
                        r.Error = "missing value for " + f;
                        return r;
                    }
                    string v = a[++i];
                    if (f == "--cond") { if (r.Cond != null) { r.Error = "--cond given twice"; return r; } r.Cond = v; }
                    else if (f == "--live") { if (r.Live != null) { r.Error = "--live given twice"; return r; } r.Live = v; }
                    else { if (r.Out != null) { r.Error = "--out given twice"; return r; } r.Out = v; }
                    continue;
                }
                r.Error = "unknown argument";
                return r;
            }
            if (r.Cond == null) { r.Error = "--cond is required"; return r; }
            if (!IsCond(r.Cond)) { r.Error = "--cond must be exactly F, E, S or A"; return r; }
            if (r.Out == null) { r.Error = "--out is required"; return r; }
            return r;
        }
    }

    // ---------------------------------------------------------------------------------------------------------------
    // ISO 8601 with a zone: yyyy-MM-ddTHH:mm:ss[.f{1,7}](Z|+HH:MM|-HH:MM). Nothing looser.
    // ---------------------------------------------------------------------------------------------------------------
    internal static class Iso
    {
        static bool Num(string s, int at, int len, out int v)
        {
            v = 0;
            if (at + len > s.Length) return false;
            for (int k = 0; k < len; k++)
            {
                char c = s[at + k];
                if (c < '0' || c > '9') return false;
                v = v * 10 + (c - '0');
            }
            return true;
        }

        internal static bool TryParse(string s, out DateTimeOffset value)
        {
            value = default(DateTimeOffset);
            if (s == null || s.Length < 20) return false;
            int y, mo, d, h, mi, se;
            if (!Num(s, 0, 4, out y) || s[4] != '-' || !Num(s, 5, 2, out mo) || s[7] != '-' || !Num(s, 8, 2, out d) || s[10] != 'T'
                || !Num(s, 11, 2, out h) || s[13] != ':' || !Num(s, 14, 2, out mi) || s[16] != ':' || !Num(s, 17, 2, out se)) return false;
            int i = 19;
            long ticks = 0;
            if (i < s.Length && s[i] == '.')
            {
                i++;
                int start = i;
                while (i < s.Length && s[i] >= '0' && s[i] <= '9') i++;
                int n = i - start;
                if (n < 1 || n > 7) return false;
                ticks = long.Parse(s.Substring(start, n).PadRight(7, '0'), NumberStyles.None, Util.CI);
            }
            TimeSpan off;
            if (i < s.Length && s[i] == 'Z') { off = TimeSpan.Zero; i++; }
            else if (i < s.Length && (s[i] == '+' || s[i] == '-'))
            {
                int oh, om;
                if (i + 6 > s.Length || !Num(s, i + 1, 2, out oh) || s[i + 3] != ':' || !Num(s, i + 4, 2, out om)) return false;
                if (oh > 14 || om > 59 || (oh == 14 && om != 0)) return false;
                off = new TimeSpan(oh, om, 0);
                if (s[i] == '-') off = off.Negate();
                i += 6;
            }
            else return false;
            if (i != s.Length) return false;
            try { value = new DateTimeOffset(y, mo, d, h, mi, se, off).AddTicks(ticks); return true; }
            catch (ArgumentException) { return false; }
        }
    }

    // ---------------------------------------------------------------------------------------------------------------
    // The arming proof (exit 3). It gates intent, not authority: its inputs are public, so it proves only that the run
    // was deliberate and names this exact exe and source.
    // ---------------------------------------------------------------------------------------------------------------
    internal sealed class ProofInfo
    {
        internal string Path, Sha256Hex, DisplayName, WrittenUtc;
        internal bool ToggledOff;
        internal readonly JArr ExtraKeys = new JArr();
    }

    internal static class Proof
    {
        internal static readonly string[] Fields = {
            "schema", "probe_exe_sha256", "probe_cs_sha256", "sublayer", "provider", "filter_key",
            "user_sid", "display_name", "expected_account", "checks_failed", "written_utc"
        };

        // Exactly the 36-character D form (TryParseExact alone trims surrounding whitespace); hex case is free.
        static bool GuidIs(object v, Guid want)
        {
            string s = v as string;
            Guid g;
            return s != null && s.Length == 36 && Guid.TryParseExact(s, "D", out g) && g == want;
        }

        internal static string DisplayNameProblem(object v)
        {
            string s = v as string;
            if (s == null) return "display_name is missing or not a string";
            if (s.Trim().Length == 0) return "display_name is empty";
            if (s.Length > K.DisplayNameMax) return "display_name is longer than 120 characters";
            foreach (char c in s) { if (char.IsControl(c)) return "display_name contains a control character"; }
            return null;
        }

        // The eleven fields, checked in order; the first that fails is named in *field*. null = armed.
        internal static string Validate(string text, string ownExeSha, string ownCsSha, DateTime nowUtc, out string field, ProofInfo info)
        {
            field = null;
            if (Toggle.Off("interlock")) { if (info != null) info.ToggledOff = true; return null; }
            object root;
            string perr = Json.TryParse(text, out root);
            if (perr != null) { field = "json"; return "the proof is not strict JSON: " + perr; }
            JObj o = root as JObj;
            if (o == null) { field = "json"; return "the proof is not a JSON object"; }

            string s = o.Get("schema") as string;
            if (s == null || !string.Equals(s, K.ProofSchema, StringComparison.Ordinal)) { field = "schema"; return "schema is not " + K.ProofSchema; }

            s = o.Get("probe_exe_sha256") as string;
            if (!Util.IsSha256Hex(ownExeSha)) { field = "probe_exe_sha256"; return "this exe's own sha256 is unavailable"; }
            if (!Util.IsSha256Hex(s) || !string.Equals(s, ownExeSha, StringComparison.OrdinalIgnoreCase)) { field = "probe_exe_sha256"; return "probe_exe_sha256 is not this exe's sha256"; }

            s = o.Get("probe_cs_sha256") as string;
            if (!Util.IsSha256Hex(ownCsSha)) { field = "probe_cs_sha256"; return "this build embeds no source sha256"; }
            if (!Util.IsSha256Hex(s) || !string.Equals(s, ownCsSha, StringComparison.OrdinalIgnoreCase)) { field = "probe_cs_sha256"; return "probe_cs_sha256 is not the source this exe was built from"; }

            if (!GuidIs(o.Get("sublayer"), K.SubLayerS2)) { field = "sublayer"; return "sublayer is not S2 " + K.SubLayerS2.ToString("D"); }
            if (!GuidIs(o.Get("provider"), K.ProviderKey)) { field = "provider"; return "provider is not " + K.ProviderKey.ToString("D"); }
            if (!GuidIs(o.Get("filter_key"), K.FilterKey)) { field = "filter_key"; return "filter_key is not " + K.FilterKey.ToString("D"); }

            s = o.Get("user_sid") as string;
            if (s == null || !string.Equals(s, K.StaleSid, StringComparison.Ordinal)) { field = "user_sid"; return "user_sid is not the recorded stale SID"; }

            object dn = o.Get("display_name");
            string dnProblem = DisplayNameProblem(dn);
            if (dnProblem != null) { field = "display_name"; return dnProblem; }

            s = o.Get("expected_account") as string;
            if (s == null || !string.Equals(s, K.ExpectedAccount, StringComparison.Ordinal)) { field = "expected_account"; return "expected_account is not " + K.ExpectedAccount; }

            JNum cf = o.Get("checks_failed") as JNum;
            if (cf == null || cf.Text != "0") { field = "checks_failed"; return "checks_failed is not the JSON integer 0"; }

            s = o.Get("written_utc") as string;
            DateTimeOffset w;
            if (s == null || !Iso.TryParse(s, out w)) { field = "written_utc"; return "written_utc is not an ISO 8601 timestamp with a zone"; }
            DateTime wu = w.UtcDateTime;
            if (wu > nowUtc + K.ProofMaxFuture) { field = "written_utc"; return "written_utc is more than 5 minutes in the future"; }
            if (nowUtc - wu > K.ProofMaxAge) { field = "written_utc"; return "written_utc is older than 24 hours"; }

            if (info != null)
            {
                info.DisplayName = (string)dn;
                info.WrittenUtc = s;
                foreach (KeyValuePair<string, object> kv in o.Items) { if (Array.IndexOf(Fields, kv.Key) < 0) info.ExtraKeys.Add(kv.Key); }
            }
            return null;
        }

        // The process-level interlock: the file checks, then Validate. Runs before any engine open.
        internal static bool Arm(string path, string ownExeSha, DateTime nowUtc, ProofInfo info, out string field, out string detail)
        {
            field = null;
            detail = null;
            if (Toggle.Off("interlock")) { info.ToggledOff = true; info.DisplayName = "ncoprobe toggle build, interlock off"; return true; }
            if (path == null) { field = "live"; detail = "--live <proof.json> is required"; return false; }
            FileInfo fi;
            try { fi = new FileInfo(path); info.Path = fi.FullName; }
            catch (Exception e) { field = "live"; detail = "the proof path is not usable (" + e.GetType().Name + ")"; return false; }
            bool isFolder;
            try { isFolder = Directory.Exists(fi.FullName); }
            catch (Exception e) { field = "live"; detail = "the proof path is not usable (" + e.GetType().Name + ")"; return false; }
            if (isFolder) { field = "live"; detail = "the proof path is a folder, not a regular file"; return false; }
            if (!fi.Exists) { field = "live"; detail = "the proof file does not exist"; return false; }
            if ((fi.Attributes & (FileAttributes.ReparsePoint | FileAttributes.Device)) != 0) { field = "live"; detail = "the proof is not a regular file (a link or a device)"; return false; }
            if (fi.Length >= K.ProofMaxBytes) { field = "live"; detail = "the proof is 1 MiB or larger"; return false; }
            byte[] b;
            try { b = File.ReadAllBytes(fi.FullName); }
            catch (Exception e) { field = "live"; detail = "the proof cannot be read (" + e.GetType().Name + ")"; return false; }
            if (b.Length >= K.ProofMaxBytes) { field = "live"; detail = "the proof is 1 MiB or larger"; return false; }
            info.Sha256Hex = Sha256.Hex(b);
            string text;
            try { text = Json.DecodeUtf8Strict(b); }
            catch (ArgumentException) { field = "json"; detail = "the proof is not valid UTF-8"; return false; }
            detail = Validate(text, ownExeSha, BuildInfo.SourceSha256, nowUtc, out field, info);
            return detail == null;
        }
    }

