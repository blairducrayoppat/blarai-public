        static string[] Cat(string[] a, string[] b)
        {
            string[] r = new string[a.Length + b.Length];
            a.CopyTo(r, 0);
            b.CopyTo(r, a.Length);
            return r;
        }

        static string[] TraceLines(string path)
        {
            if (!File.Exists(path)) return new string[0];
            List<string> r = new List<string>();
            foreach (string l in File.ReadAllText(path).Split('\n')) { if (l.Trim().Length > 0) r.Add(l.Trim()); }
            return r.ToArray();
        }

        static void ResetTrace(string path) { if (File.Exists(path)) File.Delete(path); }

        static bool BarrierSeen(Ctx x) { return File.Exists(x.Barrier) || Directory.Exists(Path.GetDirectoryName(x.Barrier)); }

        static string GitRoot(string path)
        {
            string p = Path.GetFullPath(path);
            while (!string.IsNullOrEmpty(p))
            {
                string g = Path.Combine(p, ".git");
                if (Directory.Exists(g) || File.Exists(g)) return p;
                string parent = Path.GetDirectoryName(p);
                if (parent == null || parent == p) break;
                p = parent;
            }
            return null;
        }

        static string LfSha(byte[] b)
        {
            List<byte> o = new List<byte>(b.Length);
            for (int i = 0; i < b.Length; i++) { if (b[i] == 13 && i + 1 < b.Length && b[i + 1] == 10) continue; o.Add(b[i]); }
            return Sha256.Hex(o.ToArray());
        }

        // Windows argument quoting (the rules CommandLineToArgvW and the C runtime parse).
        static string QuoteArg(string a)
        {
            if (a.Length > 0 && a.IndexOfAny(new[] { ' ', '\t', '\n', '\v', '"' }) < 0) return a;
            StringBuilder sb = new StringBuilder("\"");
            int bs = 0;
            foreach (char ch in a)
            {
                if (ch == '\\') { bs++; continue; }
                if (ch == '"') { sb.Append('\\', bs * 2 + 1); sb.Append('"'); bs = 0; continue; }
                sb.Append('\\', bs);
                bs = 0;
                sb.Append(ch);
            }
            sb.Append('\\', bs * 2);
            sb.Append('"');
            return sb.ToString();
        }

        static string Brief(Child r)
        {
            string s = "exit " + r.Code.ToString(Util.CI) + ", error=" + (r.Str("error") ?? "-") + ", field=" + (r.Str("field") ?? "-");
            if (r.TimedOut) s += ", TIMED OUT";
            if (r.StartError != null) s += ", start error " + r.StartError;
            return s;
        }

        // One child: no shell, its own console-less process, input closed, output captured. Every NCOPROBE_* variable this
        // process inherited is removed from the child's environment; the trace variable and *env* are then set.
        static Child RunChild(string exe, string[] args, string trace, Dictionary<string, string> env)
        {
            Child c = new Child();
            try
            {
                StringBuilder line = new StringBuilder();
                foreach (string a in args) { if (line.Length > 0) line.Append(' '); line.Append(QuoteArg(a)); }
                ProcessStartInfo psi = new ProcessStartInfo();
                psi.FileName = exe;
                psi.Arguments = line.ToString();
                psi.UseShellExecute = false;
                psi.CreateNoWindow = true;
                psi.RedirectStandardInput = true;
                psi.RedirectStandardOutput = true;
                psi.RedirectStandardError = true;
                List<string> inherited = new List<string>();
                foreach (string k in psi.EnvironmentVariables.Keys) { if (k.StartsWith("NCOPROBE_", StringComparison.OrdinalIgnoreCase)) inherited.Add(k); }
                foreach (string k in inherited) psi.EnvironmentVariables.Remove(k);
                psi.EnvironmentVariables[K.TraceVariable] = trace;
                if (env != null) { foreach (KeyValuePair<string, string> kv in env) psi.EnvironmentVariables[kv.Key] = kv.Value; }
                using (Process p = Process.Start(psi))
                {
                    c.Pid = p.Id;
                    p.StandardInput.Close();
                    Task<string> so = p.StandardOutput.ReadToEndAsync();
                    Task<string> se = p.StandardError.ReadToEndAsync();
                    if (!p.WaitForExit(ChildTimeoutMs))
                    {
                        c.TimedOut = true;
                        try { p.Kill(); } catch (Exception) { }
                    }
                    p.WaitForExit();
                    c.Code = p.ExitCode;
                    c.Out = so.Result;
                    c.Err = se.Result;
                }
                object j;
                if (Json.TryParse(c.Out, out j) == null) c.Json = j as JObj;
            }
            catch (Exception e) { c.StartError = Util.Describe(e); }
            return c;
        }

        // A proof planted wrong in exactly one field. Proof.Validate must refuse it naming that field, or nothing runs.
        static string WriteProof(Ctx x, string name, string text, string exeSha, string csSha, string mustFailOn)
        {
            string f;
            string why = Proof.Validate(text, exeSha, csSha, DateTime.UtcNow, out f, null);
            if (why == null) throw new InvalidOperationException("refusing to write proof '" + name + "': Proof.Validate accepts it");
            if (f != mustFailOn) throw new InvalidOperationException("proof '" + name + "' fails on '" + f + "', not on the planted '" + mustFailOn + "'");
            string path = Path.Combine(x.Proofs, name + ".json");
            File.WriteAllBytes(path, new UTF8Encoding(false).GetBytes(text));
            return path;
        }

        static Build ReadBuild(string exeDir, string flavour, bool toggle, out string problem)
        {
            problem = null;
            string dir = Path.Combine(exeDir, flavour);
            string recPath = Path.Combine(dir, "build-record-" + flavour + ".json");
            if (!File.Exists(recPath)) { problem = "no build record at " + recPath; return null; }
            object root;
            string perr = Json.TryParse(Json.DecodeUtf8Strict(File.ReadAllBytes(recPath)), out root);
            JObj r = root as JObj;
            if (perr != null || r == null) { problem = "the build record does not parse: " + perr; return null; }
            Build b = new Build();
            b.Exe = Path.Combine(dir, "ncoprobe.exe");
            b.Snapshot = Path.Combine(dir, "NcoProbe.cs");
            b.ExeSha = (r.Get("exe_sha256") as string ?? "").ToLowerInvariant();
            b.CsSha = (r.Get("cs_sha256") as string ?? "").ToLowerInvariant();
            b.Toggle = IsTrue(r.Get("toggle_build"));
            string recExe = r.Get("exe") as string;
            if (recExe == null || !string.Equals(Path.GetFullPath(recExe), Path.GetFullPath(b.Exe), StringComparison.OrdinalIgnoreCase)) { problem = "the record's exe is not " + b.Exe; return null; }
            if (!File.Exists(b.Exe) || !File.Exists(b.Snapshot)) { problem = "the exe or the source snapshot is missing in " + dir; return null; }
            if (!Util.IsSha256Hex(b.ExeSha) || !Util.IsSha256Hex(b.CsSha) || b.Toggle != toggle) { problem = "the record's hashes or toggle flag are malformed"; return null; }
            return b;
        }

