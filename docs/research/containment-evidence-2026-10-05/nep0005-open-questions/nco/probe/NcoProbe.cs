    // ---------------------------------------------------------------------------------------------------------------
    // JSON: an ordered object model, a writer that emits ASCII only, and a strict RFC 8259 parser.
    // ---------------------------------------------------------------------------------------------------------------
    internal sealed class JObj
    {
        internal readonly List<KeyValuePair<string, object>> Items = new List<KeyValuePair<string, object>>();
        internal JObj Add(string key, object value) { Items.Add(new KeyValuePair<string, object>(key, value)); return this; }
        internal bool TryGet(string key, out object value)
        {
            foreach (KeyValuePair<string, object> kv in Items) { if (kv.Key == key) { value = kv.Value; return true; } }
            value = null;
            return false;
        }
        internal object Get(string key) { object v; TryGet(key, out v); return v; }
    }

    internal sealed class JArr
    {
        internal readonly List<object> Items = new List<object>();
        internal JArr Add(object value) { Items.Add(value); return this; }
    }

