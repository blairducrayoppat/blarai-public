        static readonly string[] WfpCalls = { "FwpmEngineOpen0", "FwpmFilterAdd0", "FwpmFilterDeleteByKey0", "FwpmFilterGetByKey0", "FwpmFreeMemory0", "FwpmEngineClose0" };
        static readonly string[] ScanNames = { "directives", "wfp_call_sites", "toggle_branch", "process_start", "namespaces", "hygiene", "ipv6_layer" };

        static Regex CallRe(string name) { return new Regex(@"\bNative\s*\.\s*" + name + @"\s*\("); }

        // Every #if is exactly "#if NCOPROBE_TOGGLE"; #else, #endif and #pragma are the only other directives. Marks the lines
        // of the toggle branch and of its #else branch.
        static List<string> ScanDirectives(string[] lines, out bool[] togTrue, out bool[] togElse)
        {
            List<string> found = new List<string>();
            togTrue = new bool[lines.Length];
            togElse = new bool[lines.Length];
            List<int[]> stack = new List<int[]>();
            Regex dir = new Regex(@"^\s*#\s*(?<d>[A-Za-z]+)(?<rest>.*)$");
            string toggleName = "NCOPROBE_" + "TOGGLE";
            for (int i = 0; i < lines.Length; i++)
            {
                Match m = dir.Match(lines[i]);
                if (m.Success)
                {
                    string d = m.Groups["d"].Value, rest = m.Groups["rest"].Value.Trim();
                    if (d == "if")
                    {
                        if (rest != toggleName) found.Add("line " + (i + 1).ToString(Util.CI) + ": a conditional other than the toggle define");
                        stack.Add(new[] { rest == toggleName ? 1 : 0, 0 });
                    }
                    else if (d == "else") { if (stack.Count > 0) stack[stack.Count - 1][1] = 1; else found.Add("line " + (i + 1).ToString(Util.CI) + ": a stray else directive"); }
                    else if (d == "endif") { if (stack.Count > 0) stack.RemoveAt(stack.Count - 1); else found.Add("line " + (i + 1).ToString(Util.CI) + ": a stray endif directive"); }
                    else if (d != "pragma") found.Add("line " + (i + 1).ToString(Util.CI) + ": directive '" + d + "' is not allowed");
                    continue;
                }
                foreach (int[] f in stack) { if (f[0] == 1 && f[1] == 0) togTrue[i] = true; if (f[0] == 1 && f[1] == 1) togElse[i] = true; }
            }
            if (stack.Count != 0) found.Add("an unterminated conditional");
            return found;
        }

        static List<string> ScanWfpCallSites(string text)
        {
            List<string> found = new List<string>();
            foreach (string w in WfpCalls)
            {
                int n = CallRe(w).Matches(text).Count;
                if (n != 1) found.Add(w + " call sites: " + n.ToString(Util.CI));
            }
            foreach (Match m in Regex.Matches(text, @"\bFwpm\w+")) { if (Array.IndexOf(WfpCalls, m.Value) < 0 && !found.Contains(m.Value)) found.Add("other WFP name " + m.Value); }
            return found;
        }

        // The line span [first, last] of ProcessTest.RunChild: its signature line through the closing brace at the same
        // indentation. first = -1 when the method is not found exactly once.
        static void RunChildSpan(string[] lines, out int first, out int last)
        {
            first = -1;
            last = -1;
            Regex sig = new Regex(@"^(?<ind>\s*)static\s+Child\s+Run" + @"Child\s*\(");
            int hits = 0;
            for (int i = 0; i < lines.Length; i++)
            {
                Match m = sig.Match(lines[i]);
                if (!m.Success) continue;
                hits++;
                first = i;
                last = -1;
                string close = m.Groups["ind"].Value + "}";
                for (int j = i + 1; j < lines.Length; j++) { if (lines[j].TrimEnd() == close) { last = j; break; } }
            }
            if (hits != 1 || last < 0) { first = -1; last = -1; }
        }

        // The engine open only in the #else branch of the toggle define and the toggle sentinel only in its true branch.
        // Outside the true branch the only environment access allowed is the trace-variable read (Engine.Trace) and the
        // start-info environment block inside ProcessTest.RunChild (by the line span of that one method).
        static List<string> ScanToggleBranch(string[] lines, bool[] togTrue, bool[] togElse, int childFirst, int childLast)
        {
            List<string> found = new List<string>();
            Regex open = CallRe(WfpCalls[0]);
            Regex sentinel = new Regex(@"OpenCall\s*=\s*K\s*\.\s*" + "Toggle" + "Sentinel");
            Regex envAny = new Regex(@"\b(?:GetEnvironment" + @"Variables?|ExpandEnvironment" + @"Variables|Environment" + @"Variables)\b");
            Regex envTrace = new Regex(@"\GGetEnvironment" + @"Variable\s*\(\s*K\s*\.\s*TraceVariable\s*\)");
            Regex envChild = new Regex(@"\bpsi\s*\.\s*Environment" + @"Variables\b");
            for (int i = 0; i < lines.Length; i++)
            {
                string l = lines[i], at = "line " + (i + 1).ToString(Util.CI) + ": ";
                bool inChild = childFirst >= 0 && i >= childFirst && i <= childLast;
                if (open.IsMatch(l) && !togElse[i]) found.Add(at + "the engine open outside the non-toggle branch");
                if (sentinel.IsMatch(l) && !togTrue[i]) found.Add(at + "the toggle sentinel outside the toggle branch");
                if (togTrue[i]) continue;
                foreach (Match m in envAny.Matches(l))
                {
                    bool allowed = envTrace.Match(l, m.Index).Success;
                    if (!allowed && inChild) { foreach (Match cm in envChild.Matches(l)) { if (m.Index >= cm.Index && m.Index < cm.Index + cm.Length) allowed = true; } }
                    if (!allowed) found.Add(at + "environment access outside the toggle branch (" + m.Value + ")");
                }
            }
            return found;
        }

        // Exactly one start-info construction and one process start, both inside RunChild and the start through
        // Process.Start; the start-info type and the `psi` variable only inside RunChild, setting only allowlisted
        // properties; no process object constructed and no start-info reached through one. Construction and start are
        // also counted over the whole text, so a form split across lines is still counted.
        static List<string> ScanProcessStart(string text, string[] lines, int childFirst, int childLast)
        {
            List<string> found = new List<string>();
            if (childFirst < 0) found.Add("ProcessTest.RunChild is not found exactly once");
            string[] psiAllowed = { "FileName", "Arguments", "UseShellExecute", "CreateNoWindow", "RedirectStandardInput", "RedirectStandardOutput", "RedirectStandardError", "Environment" + "Variables" };
            string psiType = "Process" + "StartInfo";
            Regex construct = new Regex(@"\bnew\s+(?:global\s*::\s*)?(?:\w+\s*\.\s*)*" + psiType + @"\s*\(");
            Regex typeName = new Regex(@"\b" + psiType + @"\b");
            Regex anyStart = new Regex(@"\.\s*Start\s*\(");
            Regex processStart = new Regex(@"\bProcess\s*\.\s*Start\s*\(");
            Regex newProcess = new Regex(@"\bnew\s+(?:global\s*::\s*)?(?:\w+\s*\.\s*)*Process\s*\(");
            Regex startInfoProp = new Regex(@"\.\s*Start" + @"Info\b");
            Regex psiUse = new Regex(@"\bpsi\s*\.\s*(\w+)");
            int constructs = construct.Matches(text).Count, starts = anyStart.Matches(text).Count;
            if (constructs != 1) found.Add("start-info constructions: " + constructs.ToString(Util.CI));
            if (starts != 1) found.Add("process starts: " + starts.ToString(Util.CI));
            if (newProcess.IsMatch(text)) found.Add("a process object constructed");
            if (startInfoProp.IsMatch(text)) found.Add("a start-info reached through a process object");
            for (int i = 0; i < lines.Length; i++)
            {
                string l = lines[i], at = "line " + (i + 1).ToString(Util.CI) + ": ";
                bool inChild = childFirst >= 0 && i >= childFirst && i <= childLast;
                if (!inChild && typeName.IsMatch(l)) found.Add(at + "the start-info type outside RunChild");
                if (!inChild && construct.IsMatch(l)) found.Add(at + "a start-info construction outside RunChild");
                foreach (Match m in anyStart.Matches(l)) { if (!inChild || !processStart.IsMatch(l)) found.Add(at + "a process start outside RunChild or not through Process.Start"); }
                foreach (Match m in psiUse.Matches(l))
                {
                    if (!inChild) found.Add(at + "the start-info variable outside RunChild");
                    else if (Array.IndexOf(psiAllowed, m.Groups[1].Value) < 0) found.Add(at + "start-info property " + m.Groups[1].Value);
                }
            }
            return found;
        }

        static List<string> ScanNamespaces(string text)
        {
            List<string> found = new List<string>();
            string[] usingAllowed = {
                "System", "System.Collections.Generic", "System.Diagnostics", "System.Globalization", "System.IO", "System.Reflection",
                "System.Runtime.InteropServices", "System.Security.AccessControl", "System.Security.Cryptography", "System.Security.Principal",
                "System.Text", "System.Text.RegularExpressions", "System.Threading.Tasks",
            };
            foreach (Match m in Regex.Matches(text, @"(?m)^\s*using\s+(?!\()(?<ns>[^;]*);"))
            {
                string ns = Regex.Replace(m.Groups["ns"].Value, @"\s+", "");
                if (Array.IndexOf(usingAllowed, ns) < 0) found.Add("using " + ns);
            }
            string[][] denied = { new[] { "Microsoft", "Win32" }, new[] { "System", "Net" }, new[] { "System", "Management" }, new[] { "System", "DirectoryServices" }, new[] { "System", "ServiceProcess" } };
            foreach (string[] d in denied)
            {
                if (Regex.IsMatch(text, @"\b" + d[0] + @"\s*\.\s*" + d[1] + @"\b")) found.Add(d[0] + "." + d[1]);
            }
            if (Regex.IsMatch(text, @"\bRegistry" + @"\s*\.")) found.Add("a registry API");
            return found;
        }

        // The repository's own patterns: a tracker reference (research_tracker_lock), an account-domain SID other than the
        // stale SID, a Microsoft-account or Entra ID SID (identity_lock), and this tester's name and machine SID.
        static List<string> ScanHygiene(string text, string user, string domainPrefix)
        {
            List<string> found = new List<string>();
            if (Regex.IsMatch(text, @"(?<![#&])#[0-9]{3,5}(?![0-9])")) found.Add("a tracker reference");
            if (!string.IsNullOrEmpty(user) && user.Length >= 3 && text.IndexOf(user, StringComparison.OrdinalIgnoreCase) >= 0) found.Add("the operator account name");
            if (domainPrefix != null && text.IndexOf(domainPrefix, StringComparison.OrdinalIgnoreCase) >= 0) found.Add("this machine's account-domain SID");
            foreach (Match m in Regex.Matches(text, @"S-1-5-21-[0-9-]*[0-9]")) { if (m.Value != K.StaleSid) { found.Add("an account-domain SID other than the stale SID"); break; } }
            if (Regex.IsMatch(text, @"(?<![A-Za-z0-9])S-1-(?:11-96|12-1)(?:-[0-9]+)+", RegexOptions.IgnoreCase)) found.Add("a Microsoft-account or Entra ID SID");
            return found;
        }

        // FWPM_LAYER_ALE_AUTH_CONNECT_V6 (fwpmu.h) appears nowhere in the source, in D or N form.
        static List<string> ScanIpv6(string text)
        {
            List<string> found = new List<string>();
            string v6 = "4a72393b" + "-319f-44bc-84c3-" + "ba54dcb3b6b4";
            if (text.IndexOf(v6, StringComparison.OrdinalIgnoreCase) >= 0 || text.IndexOf(v6.Replace("-", ""), StringComparison.OrdinalIgnoreCase) >= 0) found.Add("the IPv6 ALE connect layer GUID");
            return found;
        }

        static Dictionary<string, List<string>> RunScans(string text, string user, string domainPrefix)
        {
            string[] lines = text.Split('\n');
            bool[] togTrue, togElse;
            Dictionary<string, List<string>> r = new Dictionary<string, List<string>>();
            r["directives"] = ScanDirectives(lines, out togTrue, out togElse);
            r["wfp_call_sites"] = ScanWfpCallSites(text);
            int childFirst, childLast;
            RunChildSpan(lines, out childFirst, out childLast);
            r["toggle_branch"] = ScanToggleBranch(lines, togTrue, togElse, childFirst, childLast);
            r["process_start"] = ScanProcessStart(text, lines, childFirst, childLast);
            r["namespaces"] = ScanNamespaces(text);
            r["hygiene"] = ScanHygiene(text, user, domainPrefix);
            r["ipv6_layer"] = ScanIpv6(text);
            return r;
        }

