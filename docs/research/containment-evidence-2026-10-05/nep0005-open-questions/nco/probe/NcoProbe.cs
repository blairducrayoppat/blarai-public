    // The filter: the user-condition security descriptor and the marshalled FWPM_FILTER0.
    // ---------------------------------------------------------------------------------------------------------------
    internal static class Sd
    {
        // A self-relative SD whose DACL holds one ACCESS_ALLOWED ACE (FWP_ACTRL_MATCH_FILTER) for *sid*.
        internal static byte[] Build(string sid)
        {
            SecurityIdentifier si = new SecurityIdentifier(sid);
            RawAcl acl = new RawAcl(2, 1);
            acl.InsertAce(0, new CommonAce(AceFlags.None, AceQualifier.AccessAllowed, (int)K.FwpActrlMatchFilter, si, false, null));
            RawSecurityDescriptor sd = new RawSecurityDescriptor(ControlFlags.DiscretionaryAclPresent, null, null, null, acl);
            byte[] b = new byte[sd.BinaryLength];
            sd.GetBinaryForm(b, 0);
            return b;
        }

        internal static string ManagedSddl(byte[] sd)
        {
            return new RawSecurityDescriptor(sd, 0).GetSddlForm(AccessControlSections.Access);
        }
    }

    // All unmanaged memory behind one FWPM_FILTER0, built BEFORE the engine is opened. BFE copies it during the add.
    internal sealed class FilterImage : IDisposable
    {
        readonly List<IntPtr> allocs = new List<IntPtr>();
        internal FWPM_FILTER0 Filter;

        IntPtr Alloc(int n) { IntPtr p = Marshal.AllocHGlobal(n); allocs.Add(p); return p; }

        internal static FilterImage Build(string displayName, byte[] sd)
        {
            FilterImage m = new FilterImage();
            try
            {
                IntPtr sdData = m.Alloc(sd.Length);
                Marshal.Copy(sd, 0, sdData, sd.Length);
                FWP_BYTE_BLOB blob = new FWP_BYTE_BLOB();
                blob.size = (uint)sd.Length;
                blob.data = sdData;
                IntPtr blobPtr = m.Alloc(Marshal.SizeOf(typeof(FWP_BYTE_BLOB)));
                Marshal.StructureToPtr(blob, blobPtr, false);

                FWPM_FILTER_CONDITION0 c = new FWPM_FILTER_CONDITION0();
                c.fieldKey = K.CondAleUserId;
                c.matchType = K.FwpMatchEqual;
                c.conditionValue.type = K.FwpSecurityDescriptorType;
                c.conditionValue.value = blobPtr;
                IntPtr condPtr = m.Alloc(Marshal.SizeOf(typeof(FWPM_FILTER_CONDITION0)));
                Marshal.StructureToPtr(c, condPtr, false);

                IntPtr provPtr = m.Alloc(16);
                Marshal.StructureToPtr(K.ProviderKey, provPtr, false);
                IntPtr weightPtr = m.Alloc(8);
                Marshal.WriteInt64(weightPtr, unchecked((long)K.Weight));
                IntPtr namePtr = Marshal.StringToHGlobalUni(displayName);
                m.allocs.Add(namePtr);

                FWPM_FILTER0 f = new FWPM_FILTER0();
                f.filterKey = K.FilterKey;
                f.displayData.name = namePtr;
                f.displayData.description = IntPtr.Zero;
                f.flags = K.FilterFlagPersistent;
                f.providerKey = provPtr;
                f.layerKey = K.LayerAleAuthConnectV4;
                f.subLayerKey = K.SubLayerS2;
                f.weight.type = K.FwpUint64;
                f.weight.value = weightPtr;
                f.numFilterConditions = 1;
                f.filterCondition = condPtr;
                f.action.type = K.ActionBlock;
                m.Filter = f;
                return m;
            }
            catch
            {
                m.Dispose();
                throw;
            }
        }

        public void Dispose()
        {
            foreach (IntPtr p in allocs) Marshal.FreeHGlobal(p);
            allocs.Clear();
        }
    }

    // ---------------------------------------------------------------------------------------------------------------
    // The engine. Open (through the trace), ONE add, read-back, ONE delete (always), read-back, close.
    // A status is null when its call threw: it is then rendered as rc null, class `other`, with the exception in `error`,
    // and never as 0 / succeeded.
    // ---------------------------------------------------------------------------------------------------------------
    internal sealed class EngineOutcome
    {
        internal bool TraceFailed;
        internal string TraceError;
        internal string OpenCall;
        internal uint? OpenRc;
        internal string OpenError;
        internal bool Opened;
        internal bool AddAttempted;
        internal uint? AddRc;
        internal ulong FilterId;
        internal string AddPresentAfter = "not_read";
        internal uint? AddGetRc;
        internal string AddError;
        internal bool DeleteAttempted;
        internal uint? DeleteRc;
        internal string DeletePresentAfter = "not_read";
        internal uint? DeleteGetRc;
        internal string DeleteError;
        internal bool Closed;
        internal uint? CloseRc;
        internal string CloseError;

        // True when every call after the open returned (whatever its status).
        internal bool SequenceComplete
        {
            get
            {
                if (!Opened) return OpenError == null;
                return AddRc.HasValue && AddGetRc.HasValue && DeleteRc.HasValue && DeleteGetRc.HasValue && CloseRc.HasValue
                    && AddError == null && DeleteError == null && CloseError == null;
            }
        }
    }

    // The calls made after the engine is open. NativeWfpCalls is the only implementation a run uses; selftest drives
    // Engine.Sequence with a fake (fake handle, never a real engine) to show how throws and statuses are recorded.
    internal interface IWfpCalls
    {
        uint Add(IntPtr h, ref FWPM_FILTER0 f, out ulong id);
        uint GetByKey(IntPtr h, ref Guid key, out IntPtr filter);
        void Free(ref IntPtr p);
        uint DeleteByKey(IntPtr h, ref Guid key);
        uint Close(IntPtr h);
    }

    internal sealed class NativeWfpCalls : IWfpCalls
    {
        public uint Add(IntPtr h, ref FWPM_FILTER0 f, out ulong id) { return Native.FwpmFilterAdd0(h, ref f, IntPtr.Zero, out id); }
        public uint GetByKey(IntPtr h, ref Guid key, out IntPtr filter) { return Native.FwpmFilterGetByKey0(h, ref key, out filter); }
        public void Free(ref IntPtr p) { Native.FwpmFreeMemory0(ref p); }
        public uint DeleteByKey(IntPtr h, ref Guid key) { return Native.FwpmFilterDeleteByKey0(h, ref key); }
        public uint Close(IntPtr h) { return Native.FwpmEngineClose0(h); }
    }

    internal static class Engine
    {
        static int s_opens;
        internal static int Opens { get { return s_opens; } }

        // Every engine open passes through here first. When the trace variable names a file, one line is appended BEFORE
        // the engine is touched; if the append fails, the caller must not touch the engine.
        static string Trace(string ctx)
        {
            s_opens++;
            string path = Environment.GetEnvironmentVariable(K.TraceVariable);
            if (string.IsNullOrEmpty(path)) return null;
            try
            {
                byte[] line = Encoding.ASCII.GetBytes("engine_open " + ctx + " pid=" + Native.GetCurrentProcessId().ToString(Util.CI)
                    + " utc=" + DateTime.UtcNow.ToString("o", Util.CI) + "\n");
                using (FileStream fs = new FileStream(path, FileMode.Append, FileAccess.Write, FileShare.Read))
                {
                    fs.Write(line, 0, line.Length);
                    fs.Flush(true);
                }
                return null;
            }
            catch (Exception e)
            {
                return "the trace file named by " + K.TraceVariable + " cannot be appended (" + e.GetType().Name + "); the engine was not touched";
            }
        }

        static bool Open(EngineOutcome o, out IntPtr h)
        {
            h = IntPtr.Zero;
            string t = Trace("FwpmEngineOpen0");
            if (t != null) { o.TraceFailed = true; o.TraceError = t; return false; }
#if NCOPROBE_TOGGLE
            o.OpenCall = K.ToggleSentinel;
            o.OpenRc = null;
            return false;
#else
            FWPM_SESSION0 s = new FWPM_SESSION0();
            s.flags = K.SessionFlags;
            s.txnWaitTimeoutInMSec = K.TxnWaitTimeoutMs;
            o.OpenCall = "FwpmEngineOpen0";
            IntPtr opened = IntPtr.Zero;
            try { o.OpenRc = Native.FwpmEngineOpen0(null, K.RpcCAuthnDefault, IntPtr.Zero, ref s, out opened); }
            catch (Exception e) { o.OpenError = Util.Describe(e); return false; }
            if (o.OpenRc.Value != 0) return false;
            h = opened;
            o.Opened = true;
            return true;
#endif
        }

        // Sets present ("true" | "false" | "unreadable") and the status for one read-back; a throw is recorded, not raised.
        static void ReadBack(IntPtr h, IWfpCalls w, out string present, out uint? rc, out string error)
        {
            present = "unreadable";
            rc = null;
            error = null;
            try
            {
                Guid key = K.FilterKey;
                IntPtr p = IntPtr.Zero;
                uint r = w.GetByKey(h, ref key, out p);
                rc = r;
                if (r == 0) { present = "true"; if (p != IntPtr.Zero) w.Free(ref p); }
                else if (r == K.FWP_E_FILTER_NOT_FOUND) present = "false";
            }
            catch (Exception e) { error = "read-back: " + Util.Describe(e); }
        }

        internal static EngineOutcome Drive(FilterImage img)
        {
            EngineOutcome o = new EngineOutcome();
            IntPtr h;
            if (!Open(o, out h)) return o;
            Sequence(o, h, img, new NativeWfpCalls());
            return o;
        }

        // Everything after a successful open. Every call is attempted in order whatever the previous one did, and the engine
        // is closed in every case.
        internal static void Sequence(EngineOutcome o, IntPtr h, FilterImage img, IWfpCalls w)
        {
            try
            {
                o.AddAttempted = true;
                try
                {
                    FWPM_FILTER0 f = img.Filter;
                    ulong id;
                    uint r = w.Add(h, ref f, out id);
                    o.AddRc = r;
                    if (r == 0) o.FilterId = id;
                }
                catch (Exception e) { o.AddRc = null; o.AddError = Util.Describe(e); }
                string present, err;
                uint? grc;
                ReadBack(h, w, out present, out grc, out err);
                o.AddPresentAfter = present;
                o.AddGetRc = grc;
                if (err != null) o.AddError = (o.AddError == null ? "" : o.AddError + "; ") + err;

                // ALWAYS, even when the add failed: deleting an absent key gives FWP_E_FILTER_NOT_FOUND, which is recorded.
                o.DeleteAttempted = true;
                try
                {
                    Guid key = K.FilterKey;
                    o.DeleteRc = w.DeleteByKey(h, ref key);
                }
                catch (Exception e) { o.DeleteRc = null; o.DeleteError = Util.Describe(e); }
                ReadBack(h, w, out present, out grc, out err);
                o.DeletePresentAfter = present;
                o.DeleteGetRc = grc;
                if (err != null) o.DeleteError = (o.DeleteError == null ? "" : o.DeleteError + "; ") + err;
            }
            finally
            {
                try { o.CloseRc = w.Close(h); o.Closed = true; }
                catch (Exception e) { o.CloseRc = null; o.CloseError = Util.Describe(e); }
            }
        }
    }

    internal static class Outcome
    {
        // Denied = ERROR_ACCESS_DENIED (0x5) or E_ACCESS_DENIED (0x80070005) only. 0x80320028 is FWP_E_OUT_OF_BOUNDS, `other`.
        // The rc stays verbatim beside the class.
        internal static bool IsDenied(uint rc) { return rc == K.ERROR_ACCESS_DENIED || rc == K.E_ACCESS_DENIED; }

        internal static string ClassifyAdd(uint rc)
        {
            if (rc == 0) return "succeeded";
            if (IsDenied(rc)) return "denied";
            return "other";
        }

        internal static string ClassifyDelete(uint rc)
        {
            if (rc == 0) return "succeeded";
            if (IsDenied(rc)) return "denied";
            if (rc == K.FWP_E_FILTER_NOT_FOUND) return "not_found";
            return "other";
        }

        // A status that is null (its call threw) is class `other`, never succeeded.
        internal static string ClassOf(uint? rc, bool delete)
        {
            if (!rc.HasValue) return "other";
            return delete ? ClassifyDelete(rc.Value) : ClassifyAdd(rc.Value);
        }

        // The add returned 0 (or threw, so it may have added), the delete did not return 0, and the delete read-back did not
        // show the filter gone: the filter may still be there although no read-back could see it.
        internal static bool PossiblyLeftBehind(EngineOutcome o)
        {
            if (!o.Opened || !o.AddAttempted) return false;
            bool added = !o.AddRc.HasValue || o.AddRc.Value == 0;
            bool deleted = o.DeleteRc.HasValue && o.DeleteRc.Value == 0;
            return added && !deleted && o.DeletePresentAfter != "false";
        }

        // trace_failed (10); incomplete (11) when the open threw; open_failed (7); filter_left_behind (8) when the delete
        // read-back still sees the filter; filter_possibly_left_behind (8) per PossiblyLeftBehind (both even if a later call
        // threw); incomplete (11) when any call after the open threw; ok (0) when the sequence ran, whatever the classes.
        internal static string Overall(EngineOutcome o, out int exit)
        {
            if (o.TraceFailed) { exit = ExitCode.PreEngineFault; return "trace_failed"; }
            if (o.OpenError != null) { exit = ExitCode.Internal; return "incomplete"; }
            if (!o.Opened) { exit = ExitCode.EngineOpenFailed; return "open_failed"; }
            if (o.DeletePresentAfter == "true") { exit = ExitCode.FilterLeftBehind; return "filter_left_behind"; }
            if (PossiblyLeftBehind(o)) { exit = ExitCode.FilterLeftBehind; return "filter_possibly_left_behind"; }
            if (!o.SequenceComplete) { exit = ExitCode.Internal; return "incomplete"; }
            exit = ExitCode.Ok;
            return "ok";
        }

        // What the probe itself saw after its delete; the admin sweep is the authority.
        internal static string Residue(EngineOutcome o)
        {
            if (!o.Opened) return "none_added";
            if (o.DeletePresentAfter == "true") return "present";
            if (o.DeletePresentAfter == "false") return "absent";
            return "unknown";
        }

        // The line the run must end with, or null. Exit 8, and exit 11 once the engine was opened, leave the filter state for
        // the session to settle; exit 12 means the window was launched as the wrong account.
        internal static string StopLineFor(EngineOutcome o, int exit)
        {
            if (exit == ExitCode.FilterLeftBehind || (exit == ExitCode.Internal && o.Opened)) return K.StopLine;
            if (exit == ExitCode.WrongPrincipal) return K.StopLineWrongPrincipal;
            return null;
        }

        static object Present(string s)
        {
            if (s == "true") return true;
            if (s == "false") return false;
            return s;
        }

        static object Hex(uint? rc) { return rc.HasValue ? (object)Util.Hex32(rc.Value) : null; }

        internal static void AddTo(JObj r, EngineOutcome o)
        {
            JObj open = new JObj().Add("call", o.OpenCall).Add("rc", Hex(o.OpenRc)).Add("opened", o.Opened).Add("error", o.OpenError)
                .Add("session_flags", K.SessionFlags).Add("txn_wait_timeout_ms", K.TxnWaitTimeoutMs);
            r.Add("engine", new JObj().Add("open", open).Add("closed", o.Closed).Add("close_rc", Hex(o.CloseRc)).Add("close_error", o.CloseError));
            JObj add = new JObj().Add("attempted", o.AddAttempted);
            if (o.AddAttempted)
            {
                add.Add("rc", Hex(o.AddRc)).Add("class", ClassOf(o.AddRc, false))
                   .Add("filter_id", o.AddRc.HasValue && o.AddRc.Value == 0 ? (object)o.FilterId : null);
            }
            if (o.Opened) add.Add("present_after", Present(o.AddPresentAfter)).Add("get_rc", Hex(o.AddGetRc));
            add.Add("error", o.AddError);
            r.Add("add", add);
            JObj del = new JObj().Add("attempted", o.DeleteAttempted);
            if (o.DeleteAttempted) del.Add("rc", Hex(o.DeleteRc)).Add("class", ClassOf(o.DeleteRc, true));
            if (o.Opened) del.Add("present_after", Present(o.DeletePresentAfter)).Add("get_rc", Hex(o.DeleteGetRc));
            del.Add("error", o.DeleteError);
            r.Add("delete", del);
            r.Add("sequence_complete", o.OpenCall == null ? null : (object)o.SequenceComplete);
        }
    }

