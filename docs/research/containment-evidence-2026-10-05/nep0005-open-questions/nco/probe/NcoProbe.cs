    // selftest-process --exe-dir <dir>: the process-level rows.
    //
    // <dir> is a build dir of build-probe.ps1 holding shipped\ and toggle\, each with its build record, exe and source
    // snapshot. The rows start those two exes as child processes under this process's own token, with refusal argument
    // vectors only, and assert each exit code, the `error` and `field` the child names, and the engine-open trace.
    //
    // ENGINE SAFETY for every shipped-exe child, three independent barriers:
    //   1. every proof is planted wrong in exactly one field and must be refused by Proof.Validate, naming that field,
    //      before it is written; otherwise the whole run aborts before any child sees it;
    //   2. --out names a folder that does not exist, so a bypassed interlock stops at the output-dir guard (exit 5);
    //   3. NCOPROBE_ENGINE_OPEN_TRACE names a file inside a folder that does not exist, so a child that reached the engine
    //      entry would end with exit 10 before the engine is touched; the trace file stays absent.
    // Toggle-exe children (that build has no engine-open call) get a writable trace file: empty for a refusal, exactly one
    // line when the engine entry was reached. The output-dir refusals need a passed interlock, so they run on the toggle
    // build only. Temporary files live in a fresh folder under the temp path, refused if it is inside a git tree, and are
    // deleted at the end (the deny entry on the denied output folder is removed first).
    // ---------------------------------------------------------------------------------------------------------------
