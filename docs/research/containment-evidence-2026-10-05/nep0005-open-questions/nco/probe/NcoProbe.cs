    internal sealed class LookupResult
    {
        internal bool Mapped;
        internal int Error;
        internal string Name, Domain;
        internal int Use;
        internal string Display { get { return string.IsNullOrEmpty(Domain) ? Name : Domain + "\\" + Name; } }
    }

    internal static class Lookup
    {
        internal static string UseLabel(int use)
        {
            switch (use)
            {
                case 1: return "user";
                case 2: return "group";
                case 3: return "domain";
                case 4: return "alias";
                case 5: return "well_known_group";
                case 6: return "deleted_account";
                case 7: return "invalid";
                case 8: return "unknown";
                case 9: return "computer";
                case 10: return "label";
                case 11: return "logon_session";
                default: return "use_" + use.ToString(Util.CI);
            }
        }

        // LookupAccountSidW. Error -1: the text is not a SID. Never throws.
        internal static LookupResult Sid(string sid)
        {
            LookupResult r = new LookupResult();
            byte[] bin;
            try
            {
                SecurityIdentifier si = new SecurityIdentifier(sid);
                bin = new byte[si.BinaryLength];
                si.GetBinaryForm(bin, 0);
            }
            catch (Exception) { r.Error = -1; return r; }
            uint cn = 256, cd = 256;
            for (int attempt = 0; attempt < 2; attempt++)
            {
                StringBuilder n = new StringBuilder((int)cn), d = new StringBuilder((int)cd);
                int use;
                if (Native.LookupAccountSid(null, bin, n, ref cn, d, ref cd, out use))
                {
                    r.Mapped = true; r.Error = 0; r.Name = n.ToString(); r.Domain = d.ToString(); r.Use = use;
                    return r;
                }
                r.Error = Marshal.GetLastWin32Error();
                if (r.Error != K.ERROR_INSUFFICIENT_BUFFER) return r;
            }
            return r;
        }

        // LookupAccountNameW. *sid* is the SID text, or null with r.Error set. Never throws.
        internal static LookupResult Name(string account, out string sid)
        {
            sid = null;
            LookupResult r = new LookupResult();
            try
            {
                uint cb = 0, cd = 0;
                int use;
                if (Native.LookupAccountName(null, account, null, ref cb, null, ref cd, out use)) { r.Error = -2; return r; }
                int e = Marshal.GetLastWin32Error();
                if (e != K.ERROR_INSUFFICIENT_BUFFER || cb == 0) { r.Error = e; return r; }
                byte[] b = new byte[cb];
                StringBuilder d = new StringBuilder((int)Math.Max(cd, 1));
                if (!Native.LookupAccountName(null, account, b, ref cb, d, ref cd, out use)) { r.Error = Marshal.GetLastWin32Error(); return r; }
                sid = new SecurityIdentifier(b, 0).Value;
                r.Mapped = true; r.Error = 0; r.Name = account; r.Domain = d.ToString(); r.Use = use;
            }
            catch (Exception) { r.Error = -1; sid = null; }
            return r;
        }
    }

    internal static class Guards
    {
        // Step 3. The stale SID must FAIL to map with ERROR_NONE_MAPPED; a mapping or any other outcome refuses.
        internal static string StaleSidProblem(bool mapped, int error)
        {
            if (Toggle.Off("stale_sid")) return null;
            if (mapped) return "the stale SID maps to an account, so the filter could match a real principal";
            if (error == K.ERROR_NONE_MAPPED) return null;
            return "the stale SID lookup ended with " + error.ToString(Util.CI) + "; only ERROR_NONE_MAPPED (1332) is accepted";
        }

        // Step 5b (exit 12, before the engine). F and E measure nco-probe itself, so they run only when the user SID is the
        // nco-probe SID; S and A are the operator's controls, so they never run as nco-probe. An unknown nco-probe SID (the
        // lookup failed) makes F and E refuse and leaves S and A free.
        internal static string PrincipalProblem(string cond, string userSid, string expectedSid)
        {
            if (Toggle.Off("principal")) return null;
            bool isExpected = userSid != null && expectedSid != null && string.Equals(userSid, expectedSid, StringComparison.Ordinal);
            if (cond == "F" || cond == "E") return isExpected ? null : "--cond " + cond + " measures nco-probe, and this token's user SID is not the nco-probe SID";
            if (cond == "S" || cond == "A") return isExpected ? "--cond " + cond + " is a control and must not run as nco-probe" : null;
            return "--cond " + (cond ?? "(none)") + " is not F, E, S or A";
        }

        // Step 4. The directory must exist and accept a test file create + delete.
        internal static string OutDirProblem(string dir, uint pid, out string full)
        {
            full = null;
            if (string.IsNullOrEmpty(dir)) return "--out is empty";
            try { full = Path.GetFullPath(dir); }
            catch (Exception e) { return "--out is not a usable path (" + e.GetType().Name + ")"; }
            if (!Directory.Exists(full)) return "the output directory does not exist";
            string test = Path.Combine(full, "case4-writetest-" + pid.ToString(Util.CI) + "-" + DateTime.UtcNow.Ticks.ToString(Util.CI) + ".tmp");
            try { using (FileStream fs = new FileStream(test, FileMode.CreateNew, FileAccess.Write, FileShare.None)) { fs.WriteByte(0x2e); } }
            catch (Exception e) { return "a test file cannot be created in the output directory (" + Util.Describe(e) + ")"; }
            try { File.Delete(test); }
            catch (Exception e) { return "the test file cannot be deleted (" + Util.Describe(e) + "): " + test; }
            if (File.Exists(test)) return "the test file is still present after delete: " + test;
            return null;
        }

        // The x64 layout the marshalling depends on (the matrix's own assertion: FWPM_FILTER0 200, condition 40).
        internal static string LayoutProblem()
        {
            if (IntPtr.Size != 8) return "not a 64-bit process";
            int f = Marshal.SizeOf(typeof(FWPM_FILTER0)), c = Marshal.SizeOf(typeof(FWPM_FILTER_CONDITION0)), s = Marshal.SizeOf(typeof(FWPM_SESSION0));
            if (f != 200) return "sizeof FWPM_FILTER0 is " + f.ToString(Util.CI) + ", not 200";
            if (c != 40) return "sizeof FWPM_FILTER_CONDITION0 is " + c.ToString(Util.CI) + ", not 40";
            if (s != 72) return "sizeof FWPM_SESSION0 is " + s.ToString(Util.CI) + ", not 72";
            return null;
        }
    }

    // ---------------------------------------------------------------------------------------------------------------
    // Token facts, all from the process's own primary token. Each read records its own Win32 error; a failed read never
    // aborts the others.
    // ---------------------------------------------------------------------------------------------------------------
    internal sealed class GroupFlags
    {
        internal bool Mandatory, EnabledByDefault, Enabled, Owner, UseForDenyOnly, Integrity, IntegrityEnabled, Resource, LogonId;

        internal static GroupFlags From(uint a)
        {
            GroupFlags g = new GroupFlags();
            g.Mandatory = (a & 0x1) != 0;
            g.EnabledByDefault = (a & 0x2) != 0;
            g.Enabled = (a & 0x4) != 0;
            g.Owner = (a & 0x8) != 0;
            g.UseForDenyOnly = (a & 0x10) != 0;
            g.Integrity = (a & 0x20) != 0;
            g.IntegrityEnabled = (a & 0x40) != 0;
            g.Resource = (a & 0x20000000) != 0;
            g.LogonId = (a & 0xC0000000) == 0xC0000000;
            return g;
        }

        internal void AddTo(JObj o)
        {
            o.Add("enabled", Enabled).Add("enabled_by_default", EnabledByDefault).Add("use_for_deny_only", UseForDenyOnly)
             .Add("integrity", Integrity).Add("integrity_enabled", IntegrityEnabled).Add("logon_id", LogonId).Add("owner", Owner)
             .Add("mandatory", Mandatory).Add("resource", Resource);
        }
    }

    internal static class Identity
    {
        const uint TOKEN_QUERY = 0x0008;
        const int TokenUser = 1, TokenGroups = 2, TokenSessionId = 12, TokenElevationType = 18, TokenLinkedToken = 19, TokenElevation = 20, TokenIntegrityLevel = 25;
        const int ERROR_BAD_LENGTH = 24;

        internal static string IntegrityLabel(string sid)
        {
            if (sid == null || !sid.StartsWith("S-1-16-", StringComparison.Ordinal)) return "not_a_mandatory_label";
            uint rid;
            if (!uint.TryParse(sid.Substring(7), NumberStyles.None, Util.CI, out rid)) return "not_a_mandatory_label";
            switch (rid)
            {
                case 0x0000: return "untrusted";
                case 0x1000: return "low";
                case 0x2000: return "medium";
                case 0x2100: return "medium_plus";
                case 0x3000: return "high";
                case 0x4000: return "system";
                case 0x5000: return "protected_process";
                default: return "rid_" + Util.Hex32(rid);
            }
        }

        internal static string ElevationTypeLabel(int v)
        {
            switch (v)
            {
                case 1: return "default";
                case 2: return "full";
                case 3: return "limited";
                default: return "unknown_" + v.ToString(Util.CI);
            }
        }

        // Variable-size class: size query, then the read. Caller frees the buffer. IntPtr.Zero + err on failure.
        static IntPtr Query(IntPtr tok, int cls, out int err, out uint size)
        {
            err = 0;
            size = 0;
            uint need;
            if (Native.GetTokenInformation(tok, cls, IntPtr.Zero, 0, out need)) { err = -2; return IntPtr.Zero; }
            int e = Marshal.GetLastWin32Error();
            if ((e != K.ERROR_INSUFFICIENT_BUFFER && e != ERROR_BAD_LENGTH) || need == 0) { err = e == 0 ? -2 : e; return IntPtr.Zero; }
            IntPtr buf = Marshal.AllocHGlobal((int)need);
            uint got;
            if (!Native.GetTokenInformation(tok, cls, buf, need, out got)) { err = Marshal.GetLastWin32Error(); Marshal.FreeHGlobal(buf); return IntPtr.Zero; }
            size = need;
            return buf;
        }

        // Fixed-size class read straight into a buffer of *len* bytes.
        static IntPtr QueryFixed(IntPtr tok, int cls, int len, out int err)
        {
            err = 0;
            IntPtr buf = Marshal.AllocHGlobal(len);
            uint got;
            if (!Native.GetTokenInformation(tok, cls, buf, (uint)len, out got)) { err = Marshal.GetLastWin32Error(); Marshal.FreeHGlobal(buf); return IntPtr.Zero; }
            return buf;
        }

        // Least data at the source: a name is looked up and recorded only for the well-known SID families below. An account
        // SID (S-1-5-21-*), a Microsoft-account SID (S-1-11-*, whose name is the person's e-mail), an Entra ID SID (S-1-12-*)
        // and every other family is recorded as a SID only, and its name is never even looked up.
        static readonly string[] ResolvablePrefixes = { "S-1-1-", "S-1-2-", "S-1-3-", "S-1-5-32-", "S-1-5-64-", "S-1-5-80-", "S-1-15-", "S-1-16-" };

        internal static bool NameMayBeResolved(string sid)
        {
            if (sid == null) return false;
            foreach (string p in ResolvablePrefixes) { if (sid.StartsWith(p, StringComparison.Ordinal)) return true; }
            // S-1-5-<rid>: exactly one sub-authority under the NT authority, and a small one (S-1-5-11, S-1-5-18, S-1-5-113 ...).
            if (sid.StartsWith("S-1-5-", StringComparison.Ordinal))
            {
                string rest = sid.Substring(6);
                uint rid;
                return rest.Length >= 1 && rest.Length <= 3 && uint.TryParse(rest, NumberStyles.None, Util.CI, out rid);
            }
            return false;
        }

        // One TOKEN_GROUPS entry. *lookup* is LookupAccountSidW in a run and a fake in selftest.
        internal static JObj GroupEntry(string sid, uint attrs, Func<string, LookupResult> lookup)
        {
            JObj it = new JObj().Add("sid", sid).Add("attributes", Util.Hex32(attrs));
            GroupFlags.From(attrs).AddTo(it);
            if (NameMayBeResolved(sid))
            {
                LookupResult r = lookup(sid);
                it.Add("name", r.Mapped ? r.Display : null).Add("sid_type", r.Mapped ? Lookup.UseLabel(r.Use) : null).Add("lookup_error", r.Error);
            }
            else it.Add("name", null).Add("name_withheld", true);
            return it;
        }

        static JObj Membership(string sid, JObj item, bool groupsRead)
        {
            JObj m = new JObj().Add("sid", sid);
            if (!groupsRead) { m.Add("present", "unreadable"); return m; }
            if (item == null) { m.Add("present", false); return m; }
            m.Add("present", true);
            foreach (KeyValuePair<string, object> kv in item.Items) { if (kv.Key != "sid") m.Add(kv.Key, kv.Value); }
            return m;
        }

        // Adds every token fact to *o*; returns the user SID, or null when it could not be read. *expectedSid* is the
        // nco-probe SID (LookupAccountName), or null when the lookup failed.
        internal static string AddFacts(JObj o, out string expectedSid)
        {
            IntPtr tok = IntPtr.Zero;
            int openErr = 0;
            try { if (!Native.OpenProcessToken(Native.GetCurrentProcess(), TOKEN_QUERY, out tok)) { openErr = Marshal.GetLastWin32Error(); tok = IntPtr.Zero; } }
            catch (Exception) { openErr = -1; tok = IntPtr.Zero; }
            o.Add("token_open", new JObj().Add("ok", tok != IntPtr.Zero).Add("error", openErr));
            string userSid = null;
            try
            {
                // user
                JObj u = new JObj();
                try
                {
                    if (tok == IntPtr.Zero) u.Add("error", openErr);
                    else
                    {
                        int err; uint size;
                        IntPtr buf = Query(tok, TokenUser, out err, out size);
                        if (buf == IntPtr.Zero) u.Add("error", err);
                        else
                        {
                            try
                            {
                                string sid = new SecurityIdentifier(Marshal.ReadIntPtr(buf, 0)).Value;
                                // The user is recorded by SID only (no name lookup): is_expected_account says who it is.
                                u.Add("sid", sid).Add("attributes", Util.Hex32(unchecked((uint)Marshal.ReadInt32(buf, IntPtr.Size))));
                                u.Add("error", 0);
                                userSid = sid;
                            }
                            finally { Marshal.FreeHGlobal(buf); }
                        }
                    }
                }
                catch (Exception e) { u.Add("exception", Util.Describe(e)); userSid = null; }
                o.Add("user", u).Add("user_sid", userSid);

                // groups
                JObj g = new JObj();
                JArr items = new JArr();
                JObj nco = null, adm = null;
                bool groupsRead = false;
                try
                {
                    if (tok == IntPtr.Zero) g.Add("error", openErr);
                    else
                    {
                        int err; uint size;
                        IntPtr buf = Query(tok, TokenGroups, out err, out size);
                        if (buf == IntPtr.Zero) g.Add("error", err);
                        else
                        {
                            try
                            {
                                int count = Marshal.ReadInt32(buf, 0);
                                long needed = IntPtr.Size + (long)count * 2 * IntPtr.Size;
                                if (count < 0 || needed > size) g.Add("error", -3).Add("error_detail", "TOKEN_GROUPS count does not fit the buffer");
                                else
                                {
                                    for (int i = 0; i < count; i++)
                                    {
                                        IntPtr entry = new IntPtr(buf.ToInt64() + IntPtr.Size + (long)i * 2 * IntPtr.Size);
                                        string sid = new SecurityIdentifier(Marshal.ReadIntPtr(entry, 0)).Value;
                                        uint attrs = unchecked((uint)Marshal.ReadInt32(entry, IntPtr.Size));
                                        JObj it = GroupEntry(sid, attrs, Lookup.Sid);
                                        items.Add(it);
                                        if (sid == K.NcoGroupSid) nco = it;
                                        if (sid == K.AdministratorsSid) adm = it;
                                    }
                                    g.Add("error", 0).Add("count", count);
                                    groupsRead = true;
                                }
                            }
                            finally { Marshal.FreeHGlobal(buf); }
                        }
                    }
                }
                catch (Exception e) { g.Add("exception", Util.Describe(e)); groupsRead = false; }
                g.Add("items", items);
                o.Add("groups", g);
                o.Add("nco_group", Membership(K.NcoGroupSid, nco, groupsRead));
                o.Add("administrators", Membership(K.AdministratorsSid, adm, groupsRead));

                // integrity level
                JObj il = new JObj();
                try
                {
                    if (tok == IntPtr.Zero) il.Add("error", openErr);
                    else
                    {
                        int err; uint size;
                        IntPtr buf = Query(tok, TokenIntegrityLevel, out err, out size);
                        if (buf == IntPtr.Zero) il.Add("error", err);
                        else
                        {
                            try
                            {
                                string sid = new SecurityIdentifier(Marshal.ReadIntPtr(buf, 0)).Value;
                                il.Add("sid", sid).Add("label", IntegrityLabel(sid)).Add("attributes", Util.Hex32(unchecked((uint)Marshal.ReadInt32(buf, IntPtr.Size)))).Add("error", 0);
                            }
                            finally { Marshal.FreeHGlobal(buf); }
                        }
                    }
                }
                catch (Exception e) { il.Add("exception", Util.Describe(e)); }
                o.Add("integrity", il);

                // elevation type, elevation, linked token, session id
                o.Add("elevation_type", ReadInt(tok, openErr, TokenElevationType));
                o.Add("elevation", ReadInt(tok, openErr, TokenElevation));
                o.Add("linked_token", ReadLinked(tok, openErr));
                o.Add("session_id", ReadInt(tok, openErr, TokenSessionId));
            }
            finally { if (tok != IntPtr.Zero) Native.CloseHandle(tok); }

            // The nco-probe SID. The account's domain (this machine's name) is not recorded.
            LookupResult ea = Lookup.Name(K.ExpectedAccount, out expectedSid);
            JObj eo = new JObj().Add("name", K.ExpectedAccount).Add("sid", expectedSid)
                .Add("sid_type", ea.Mapped ? Lookup.UseLabel(ea.Use) : null).Add("error", ea.Error);
            string forced = Toggle.ExpectedSidOverride();
            if (forced != null) { expectedSid = forced; eo = new JObj().Add("name", K.ExpectedAccount).Add("sid", forced).Add("sid_type", null).Add("error", 0).Add("toggle_override", true); }
            o.Add("expected_account", eo);
            o.Add("is_expected_account", userSid != null && expectedSid != null && string.Equals(userSid, expectedSid, StringComparison.Ordinal));
            return userSid;
        }

        static JObj ReadInt(IntPtr tok, int openErr, int cls)
        {
            JObj r = new JObj();
            try
            {
                if (tok == IntPtr.Zero) { r.Add("error", openErr); return r; }
                int err;
                IntPtr buf = QueryFixed(tok, cls, 4, out err);
                if (buf == IntPtr.Zero) { r.Add("error", err); return r; }
                try
                {
                    int v = Marshal.ReadInt32(buf, 0);
                    if (cls == TokenElevationType) r.Add("value", v).Add("label", ElevationTypeLabel(v));
                    else if (cls == TokenElevation) r.Add("elevated", v != 0);
                    else r.Add("value", v);
                    r.Add("error", 0);
                }
                finally { Marshal.FreeHGlobal(buf); }
            }
            catch (Exception e) { r.Add("exception", Util.Describe(e)); }
            return r;
        }

        // Presence only: the handle is closed at once.
        static JObj ReadLinked(IntPtr tok, int openErr)
        {
            JObj r = new JObj();
            try
            {
                if (tok == IntPtr.Zero) { r.Add("present", false).Add("error", openErr); return r; }
                int err;
                IntPtr buf = QueryFixed(tok, TokenLinkedToken, IntPtr.Size, out err);
                if (buf == IntPtr.Zero) { r.Add("present", false).Add("error", err); return r; }
                try
                {
                    IntPtr h = Marshal.ReadIntPtr(buf, 0);
                    r.Add("present", h != IntPtr.Zero).Add("error", 0);
                    if (h != IntPtr.Zero) r.Add("closed", Native.CloseHandle(h));
                }
                finally { Marshal.FreeHGlobal(buf); }
            }
            catch (Exception e) { r.Add("exception", Util.Describe(e)); }
            return r;
        }
    }

