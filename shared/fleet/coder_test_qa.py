class _TokeniserUnavailable(Exception):
    """:mod:`oracle_qa` could not be imported, so no node file was read.

    Raised rather than returning ``[]`` on purpose. An import failure that yields "no
    findings" is a control degrading into a pass, and the caller has to be able to record
    the file as UNPARSED — the same fail-soft-is-not-fail-silent rule the PowerShell
    wrapper holds one layer up."""


def _node_tokeniser():
    """The five entry points :mod:`oracle_qa` exports for reuse (its #1348 seam).

    Imported lazily: :mod:`oracle_qa` is ~2,300 lines and every python-only dispatch would
    otherwise pay for it to grade a tree containing no javascript at all."""
    try:
        from shared.fleet import oracle_qa
    except Exception as exc:  # pragma: no cover — exercised via the unavailability lock
        raise _TokeniserUnavailable(str(exc)) from exc
    return oracle_qa


#: CommonJS first-party binding: ``const { a, b } = require('../src/x.js')`` or
#: ``const x = require('./y')``. A RELATIVE specifier is first-party by construction, the
#: same rule :func:`oracle_qa.node_first_party_names` applies to ESM.
_NODE_REQUIRE_RE = re.compile(
    r"(?:const|let|var)\s+(?P<clause>\{[^}]*\}|[A-Za-z_$][\w$]*)\s*=\s*"
    r"require\s*\(\s*(?P<q>['\"])(?P<spec>\.[^'\"]*)(?P=q)\s*\)"
)

#: A dynamically-imported first-party binding: ``const { a } = await import('./x')``. The
#: static twin was covered from the start and this was not, so the same test was convicted
#: or spared by whether its import was static — the smaller residue of the same defect.
_NODE_DYNIMPORT_RE = re.compile(
    r"(?:const|let|var)\s+(?P<clause>\{[^}]*\}|[A-Za-z_$][\w$]*)\s*=\s*"
    r"(?:await\s+)?import\s*\(\s*(?P<q>['\"])(?P<spec>\.[^'\"]*)(?P=q)\s*\)"
)

#: Modifiers that may precede a declaration, as ONE definition shared by every pattern that
#: has to recognise one. Maintained in parallel until 2026-08-16, and they drifted exactly as
#: that always does: `abstract class` landed on the class alternative only, so a nested
#: `abstract class` was STRIPPED from its enclosing body while a top-level one was never
#: admitted — two readers of the same construct inside one module, disagreeing. That is the
#: hazard :mod:`oracle_qa`'s tokeniser comment names, at declaration level instead of token
#: level, and one definition is the answer to it.
_DECL_MODIFIERS = r"(?:export\s+)?(?:default\s+)?(?:abstract\s+)?(?:async\s+)?"
#: ``function``, ``async function``, ``function*`` — the generator star included, because
#: ``function\s+NAME`` cannot cross it.
_FN_KEYWORD = r"function\s*\*?\s*"
_IDENT = r"[A-Za-z_$][\w$]*"

#: A symbol DECLARED IN THIS FILE: ``function f``, ``async function f``, ``class C``, and
#: ``const f = (…) =>`` / ``= function``. Deliberately not every ``const`` — only bindings
#: that are callable, because the question being asked is "can this call throw".
#:
#: SIX defects have been "a declaration form this reader does not recognise", each convicting
#: the test that called a helper which plainly asserts: a generator, ``abstract class``,
#: ``export abstract class``, ``export default class``, ``export default function`` and
#: ``export default async function``. None announced itself; every one was found by running
#: ordinary javascript through the scanner. The durable control is not this pattern getting
#: longer — it is :func:`test_every_declaration_FORM_admits_its_symbol`, which enumerates the
#: forms so the next unrecognised spelling fails a test instead of a delivery.
_NODE_LOCAL_DECL_RE = re.compile(
    rf"(?:^|[;{{}}\n])\s*{_DECL_MODIFIERS}{_FN_KEYWORD}(?P<fn>{_IDENT})"
    rf"|(?:^|[;{{}}\n])\s*{_DECL_MODIFIERS}class\s+(?P<cls>{_IDENT})"
    rf"|(?:^|[;{{}}\n])\s*{_DECL_MODIFIERS}(?:const|let|var)\s+(?P<v>{_IDENT})\s*=\s*"
    rf"(?:async\s*)?(?:{_FN_KEYWORD}|\([^)]*\)\s*=>|{_IDENT}\s*=>)"
)

#: How far past a declaration head to look for its body before giving up. A guard against
#: a pathological source, not a semantic limit.
_DECL_BODY_SCAN = 400


#: A nested NAMED declaration inside another declaration's body. Stripped before the body is
#: searched, because ``function outer() { function inner(h) { assert.ok(h); } return 1; }``
#: otherwise earns ``outer`` an exemption it has not got — ``outer()`` cannot fail for any
#: implementation, and the assertion belongs to a symbol the test never calls. ``inner`` is
#: still admitted in its own right; only the borrowing stops. Deliberately named
#: declarations only: an inline callback (``items.forEach(i => assert.ok(i))``) IS part of
#: what the enclosing function does when called, and must keep counting.
#:
#: The ARROW alternative is not decoration. Without it, ``function outer() { const inner =
#: (h) => assert.ok(h); return 1; }`` spared ``outer`` while the ``function inner`` spelling
#: of the same code convicted it — identical semantics, opposite verdicts, chosen by which
#: form the coder happened to write. Structurally the same asymmetry as the CommonJS-versus-
#: ESM one this module already fixed once, so it is fixed the same way.
_NODE_NESTED_DECL_RE = re.compile(
    rf"\b{_DECL_MODIFIERS}(?:{_FN_KEYWORD}|class\s+){_IDENT}"
    rf"|\b{_DECL_MODIFIERS}(?:const|let|var)\s+{_IDENT}\s*=\s*"
    rf"(?:async\s*)?(?:{_FN_KEYWORD}|\([^)]*\)\s*=>|{_IDENT}\s*=>)"
)


def _strip_nested_declarations(body: str) -> str:
    """Remove nested NAMED declarations from a declaration body.

    Named only: an inline callback (``items.forEach(i => assert.ok(i))``) IS part of what the
    enclosing function does when called and must keep counting, while a helper bound to a
    name and never called is borrowing an assertion the caller never reaches.

    Spans, not text search. The first version re-located each nested body with
    ``body.find(...)``, and a body whose text also occurs inside its own HEAD — ``function
    inner(o = { assert: 1 }) { assert: 1 }`` — made the search land in the head and strip the
    wrong span, leaving the token behind. The offset was already known; re-deriving it was
    the entire defect."""
    out: list[str] = []
    i = 0
    for m in _NODE_NESTED_DECL_RE.finditer(body):
        if m.start() < i:
            continue
        is_arrow = m.group(0).rstrip().endswith("=>")
        start, end = _declaration_span(body, m.end(), skip_head=not is_arrow)
        out.append(body[i:m.start()])
        i = max(end if end >= 0 else m.end(), m.end())
    out.append(body[i:])
    return "".join(out)


def _declaration_body(masked: str, pos: int, *, skip_head: bool = True) -> str:
    """The body of the declaration whose head ends at ``pos``, read from MASKED source.

    Brace-matched when the declaration has a block body, and taken to the end of the
    statement when it is an expression arrow (``const f = () => x``). Masked rather than raw
    because a brace inside a string literal would otherwise unbalance the match.

    Returns ``""`` when no body can be found, which is treated as "cannot show this can
    throw" — the conservative direction, since the caller uses a body to EARN an exemption.

    **The whole declaration HEAD is skipped before the body is looked for**, and this took
    three attempts because the head has more shapes than it looks like it does. The rule is:
    consume identifiers and balanced parentheses until a ``{`` is reached. Each shape below
    broke a version that handled the one before it, and every one was a HARD false positive —
    a helper whose body plainly asserts, failing to earn its exemption, so the test calling
    it was convicted:

      * ``function checkPiece(piece, opts = {strict: true}) { assert.ok(...) }`` — the first
        ``{`` in source order belongs to the DEFAULT PARAMETER, not the body.
      * ``const f = function helper(html, opts = {strict: true}) { assert.ok(...) }`` — the
        same defect wearing a name: the parameter skip fired only when a ``(`` came next, and
        for a NAMED function expression the next token is the function's own name.
      * ``class Checker extends mixin({strict: true}) { run(h) { assert.ok(h); } }`` — the
        ``extends`` call's argument, same root cause a third time.

    ``skip_head`` is False for an arrow, whose head the calling regex has already consumed;
    skipping identifiers there would eat the first token of an expression body."""
    start, end = _declaration_span(masked, pos, skip_head=skip_head)
    return masked[start:end] if start >= 0 else ""


def _balanced(masked: str, i: int, opener: str, closer: str) -> int:
    """Index just past the group opening at ``i``, or ``len(masked)`` if it never closes.

    **The unclosed case is indistinguishable from success at the call site**, and that shape
    has bitten this file before. It is safe here only because of where the callers stand: an
    unclosed group runs ``i`` to the end, the body scan then finds nothing, and the symbol
    silently fails to earn its exemption — the CONSERVATIVE direction, a false positive
    rather than a false clean. A future caller that reads it the other way round would invert
    that, so the failure mode is named here rather than left to be rediscovered."""
    n = len(masked)
    depth = 0
    while i < n:
        if masked[i] == opener:
            depth += 1
        elif masked[i] == closer:
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return n


def _declaration_span(masked: str, pos: int, *, skip_head: bool = True) -> "tuple[int, int]":
    """``(start, end)`` of the declaration body, or ``(-1, -1)``.

    Offsets rather than text, because :func:`_strip_nested_declarations` previously located
    the body it had just extracted by searching for that text again — and a body whose text
    also occurs inside its own HEAD made the search land in the head and strip the wrong
    span. The offset was known all along; re-deriving it was the whole defect."""
    n = len(masked)
    i = pos
    if skip_head:
        # Walk the declaration head to its END rather than to its first brace. Six separate
        # shapes have now put a `{` in front of the body — a default parameter, a named
        # function expression's own name, an `extends` call's argument, a TypeScript object
        # RETURN TYPE, an object GENERIC CONSTRAINT, and a TYPE PREDICATE (`: x is {…}`) —
        # and each fix that special-cased one of them left the next reachable. The rule that
        # covers all six: a brace group is the BODY unless a return-type annotation is still
        # open, in which case it is the type and the body is the next one.
        saw_annotation = False
        body_span: "tuple[int, int] | None" = None
        while i < n:
            while i < n and masked[i] in " \t\r\n":
                i += 1
            if i >= n:
                break
            ch = masked[i]
            if ch.isalnum() or ch in "_$":
                while i < n and (masked[i].isalnum() or masked[i] in "_$"):
                    i += 1
                continue
            if ch == "(":
                i = _balanced(masked, i, "(", ")")
                continue
            if ch == "<":
                # A generic parameter list. Angles are counted, and any braces INSIDE the
                # constraint are consumed with it.
                i = _balanced(masked, i, "<", ">")
                continue
            if ch == "[":
                # BALANCED, not a single character. Consuming `[` alone made the walk break
                # at the comma inside a tuple return type — `: [string, { ok: boolean }]` —
                # and the object member of the tuple was then read as the body. Every
                # bracketing construct in a head has to be balanced; treating one of them as
                # a token is how the seventh instance of this defect happened.
                i = _balanced(masked, i, "[", "]")
                continue
            if ch in ":|&.?":
                # A return-type annotation and the type operators that may follow it.
                # `|` and `&` REOPEN it: after `: { a: 1 } | { b: 2 } { body }` the first
                # group is a type, and without this the second group was taken as the body
                # while the real body sat one group further on. Root cause nine.
                if ch in ":|&":
                    saw_annotation = True
                i += 1
                continue
            if ch == "{":
                close = _balanced(masked, i, "{", "}")
                body_span = (i, close)
                i = close
                if not saw_annotation:
                    break  # no annotation is open, so this group IS the body
                saw_annotation = False  # that group was the type; the next one is the body
                continue
            break
        if body_span is not None:
            return body_span
    pos = i
    limit = min(n, pos + _DECL_BODY_SCAN)
    open_at = -1
    while i < limit:
        ch = masked[i]
        if ch == "{":
            open_at = i
            break
        if ch == ";":
            break
        i += 1
    if open_at < 0:
        # Expression-bodied arrow: everything up to the end of the statement.
        end = pos
        while end < n and masked[end] not in ";\n":
            end += 1
        return (pos, end)
    close = _balanced(masked, open_at, "{", "}")
    if close > n:
        return (-1, -1)
    return (open_at, close)


def node_source_is_readable(code: str) -> bool:
    """Whether the node tokeniser can actually READ this source.

    Exists because :func:`scan_node_source` is fail-soft and returns ``[]`` for a source it
    could not mask — which is indistinguishable, at the call site, from a clean exam. Any
    caller that BANKS a count has to be able to tell those apart; :func:`scan_paths` could
    not, and recorded an unreadable file as examined-and-clean.

    Raises :class:`_TokeniserUnavailable` for the same reason that function does: a missing
    scanner is a different fact from an unreadable file, and neither is "nothing found"."""
    return _node_tokeniser().node_mask(code) is not None


def _node_callable_symbols(code: str, oq) -> set[str]:
    """Every name whose call could throw on a missing or wrong implementation.

    A superset of :func:`oracle_qa.node_first_party_names`, and the difference is the point.
    That function answers "what did this file import from a relative path", which is the
    right question for a SEALED oracle — authored to a template, against a module it does
    not own. A coder's own exam is not written to that template, and two ordinary shapes
    fell outside it (#1416, both found by an independent reviewer, both HARD false
    positives that would have withdrawn a review skip):

      * **the assertion lives in a helper defined in the SAME file.** ``function
        checkContains(html, n) { assert.ok(...) }`` called from the test body — a file
        containing ``assert.ok`` was told it "makes no assertion".
      * **CommonJS.** ``const { computeTotal } = require('../src/cart.js')`` bound nothing,
        so the identical test was convicted or spared purely by import syntax — and the
        bare no-raise smoke test that :func:`scan_node_source` documents as deliberately
        exempt was unreachable for every ``require()`` file.

    Kept HERE rather than widened in ``oracle_qa`` on purpose: this loosens a sparing rule,
    and loosening it for the sealed-oracle grader is a separate judgement with a separate
    blast radius. The tokeniser itself stays shared and single.

    **An imported or required symbol earns its exemption structurally**: it names an
    implementation this file does not own, so the call throws when that implementation is
    missing or wrong. **A locally-declared one has to earn it, and the test is its OWN
    BODY** — does that body assert, or call something external? ``function checkContains(h,
    n) { assert.ok(...) }`` earns it; ``function samplePiece() { return {name: 'bowl'} }``
    does not, and neither does ``const build = () => ({ok: true})``.

    Two earlier versions of this rule were wrong in opposite directions, and the second is
    the instructive one. The first counted every local declaration, which spared ``function
    noop() {}`` called from a test body — a call that cannot fail for any implementation.
    The fix for that asked *"does the FILE assert anywhere"*, which is a FILE-level answer to
    a PER-TEST question: one real assertion anywhere in a multi-test exam re-opened the hole
    for every other test in it, and a multi-test file with one weak test is the normal shape
    this instrument exists to catch. Worse, the closure could be declared inside the vacuous
    body itself. Both were found by an independent reviewer; the second had a docstring
    claiming it "drops the shape it must not spare" and a lock that certified that sentence
    while exercising only the no-assertion-anywhere case — a lock passing for a narrower
    reason than its claim, which is its own defect class."""
    masked = oq.node_mask(code)
    if masked is None:
        masked = code
    external: set[str] = set(oq.node_first_party_names(code))
    for pattern in (_NODE_REQUIRE_RE, _NODE_DYNIMPORT_RE):
        for m in pattern.finditer(code):
            clause = m.group("clause")
            if clause.startswith("{"):
                for part in clause.strip("{}").split(","):
                    bound = part.split(":")[-1].strip()
                    if bound:
                        external.add(bound)
            else:
                external.add(clause.strip())

    locals_: dict[str, str] = {}
    for m in _NODE_LOCAL_DECL_RE.finditer(masked):
        name = m.group("fn") or m.group("cls") or m.group("v")
        if not name:
            continue
        # An arrow's head is already consumed by the regex; anything else still has one.
        is_arrow = m.group(0).rstrip().endswith("=>")
        body = _declaration_body(masked, m.end(), skip_head=not is_arrow)
        if body:
            locals_.setdefault(name, _strip_nested_declarations(body))

    # Fixed point, because delegation nests. `outer()` calls `inner()` which asserts, and a
    # one-level rule convicted the test that called `outer` — the helper-of-a-helper is an
    # ordinary shape and a scanner that punishes it is teaching people to inline. Iterating
    # to stability costs nothing at file scale and removes the whole class rather than the
    # one case that happened to be constructed.
    names = set(external)
    changed = True
    while changed:
        changed = False
        for name, body in locals_.items():
            if name in names:
                continue
            # A CALL, never a bare property read. `\(|\.` also matched `cart.title`, and
            # reading a property off an imported object does not throw on a missing or wrong
            # implementation the way calling it does. This is now the same predicate
            # `scan_node_source` applies to a test body, which is the point: the two were
            # answering the same question with different strictness.
            if oq.NODE_ASSERTION_RE.search(body) or any(
                re.search(r"\b" + re.escape(sym) + r"\s*(?:\(|\.\s*\w+\s*\()", body)
                for sym in names
            ):
                names.add(name)
                changed = True
    return names


def scan_node_source(code: str, *, path: str = "") -> list[CoderTestFinding]:
    """The node dual of :func:`scan_vacuous_tests`: a test that cannot fail.

    Two per-test shapes, both taken from :func:`oracle_qa.node_static_vacuity` so the two
    instruments cannot drift apart on what a test body contains:

      * an EMPTY body — it cannot fail on any tree, for any implementation, ever;
      * a body with no assertion AND no call of a first-party symbol — nothing in it can
        throw on a missing implementation, so it cannot discriminate either.

    Deliberately NOT flagged, and this is :mod:`oracle_qa`'s established rule rather than a
    new leniency: an assertion-free body that DOES call a first-party symbol. That is the
    bare no-raise smoke test, it genuinely fails on a skeleton because the call throws, and
    hard-flagging it would contradict a rule written to prevent a false flag.

    One shape python does not need, and the reason it is here. Pytest's collection contract
    is ``def test_*``, so a python file with no test functions is visibly empty. Node has no
    such contract — a ``.test.mjs`` may be a bare script — and the 08-14 delivery shipped
    exactly that: ``tests/data.test.mjs`` calls two functions inside a ``try``, logs, and
    prints "All tests passed!" if nothing throws. Zero test bodies means a per-test scan
    convicts nothing, which is the clean-looking zero this module exists to refuse. So a
    file whose NAME declares it an exam, which declares no test and asserts nothing
    anywhere, is convicted at file level.

    Fail-soft on syntax, never fail-silent on machinery: an unmaskable source yields ``[]``
    (``node --check`` owns syntax and will already be red), but a MISSING tokeniser raises,
    because "nobody could look" must not read as "nothing was found".

    Callers that BANK a result must ask :func:`node_source_is_readable` first — a bare ``[]``
    from here cannot be told apart from a clean exam, and :func:`scan_paths` counted one as
    the other until 2026-08-16."""
    oq = _node_tokeniser()
    masked = oq.node_mask(code)
    if masked is None:
        return []

    findings: list[CoderTestFinding] = []
    bodies = oq.node_test_bodies(masked)
    first_party = _node_callable_symbols(code, oq)

    for idx, (offset, body) in enumerate(bodies, start=1):
        subject = oq.node_declared_name(code, offset) or f"test #{idx}"
        if not body.strip():
            findings.append(CoderTestFinding(
                CLASS_VACUOUS_TEST,
                f"`{subject}` has an EMPTY body — it asserts nothing and cannot fail on "
                "any tree, for any implementation, so its green carries no information "
                "about whether the behaviour is correct",
                subject=subject,
            ))
            continue
        if oq.NODE_ASSERTION_RE.search(body):
            continue
        if any(
            re.search(r"\b" + re.escape(name) + r"\s*(?:\(|\.\s*\w+\s*\()", body)
            for name in first_party
        ):
            continue  # the bare no-raise smoke test — oracle_qa's own floor rule
        findings.append(CoderTestFinding(
            CLASS_VACUOUS_TEST,
            f"`{subject}` makes no assertion and calls no first-party symbol — nothing in "
            "it can fail on a missing implementation, so it passes whether the code works "
            "or not",
            subject=subject,
        ))

    # FILE level. Only for a self-declared exam, and only when the file contains no test
    # AND asserts nothing anywhere — a bare script with a top-level assertion CAN fail
    # under `node --test`, so it is a real if unusual exam and is left alone.
    if path and node_exam_by_name(path) and not bodies and not oq.NODE_ASSERTION_RE.search(masked):
        findings.append(CoderTestFinding(
            CLASS_VACUOUS_TEST,
            "this file is named as an exam but declares no test and makes no assertion — "
            "it passes unless the code throws, so its green says nothing about whether the "
            "behaviour is correct",
            subject=path,
        ))

    if path:
        findings = [
            replace(f, subject=f"{path}::{f.subject}" if f.subject and f.subject != path
                    else path)
            for f in findings
        ]
    return findings


def scan_paths(paths: "Sequence[str]", *,
               uncovered: "Sequence[str] | None" = None) -> CoderTestQAResult:
    """Scan a set of test files on disk. Unreadable/unparseable files are recorded and
    skipped — a broken test file is the TEST gate's business, already red there.

    ``measured`` is set only when at least one file was actually READ AND PARSED. An empty
    path list, a tree whose files all failed to open, or a suite that is entirely
    unparseable all yield ``measured=False``: each is an unexamined project, and an
    unexamined project must not be able to read as an examined one that found nothing.

    #1416: the language is chosen per file from its suffix, and a file in NEITHER language
    never reaches here — it arrives via ``uncovered`` and is named, not counted. The two
    are different facts and the whole ticket is about not collapsing them."""
    from pathlib import Path

    result = CoderTestQAResult()
    result.uncovered = [str(u) for u in (uncovered or [])]
    result.languages = {LANG_PYTHON: 0, LANG_NODE: 0}
    parsed = 0
    for raw in paths:
        p = Path(raw)
        try:
            code = p.read_text(encoding="utf-8", errors="replace")
        except OSError:
            result.unparsed.append(str(p))
            continue
        suffix = p.suffix.lower()
        result.files_scanned += 1
        if suffix in NODE_TEST_SUFFIXES:
            try:
                # Two DIFFERENT ways this file can go unexamined, and both were being banked
                # as an examined-and-clean file until 2026-08-16 (#1416, found in review):
                # the tokeniser missing, and the tokeniser REFUSING this source. The python
                # branch below has always routed its parse failure to `unparsed`; the node
                # branch incremented `parsed` and the language count unconditionally, so an
                # unmaskable file banked as `files_scanned: 1, measured: true, clean` — with
                # a genuinely empty-bodied test inside it still reported as clean. That is
                # this module's own defect, one seam inside the fix for it.
                if not node_source_is_readable(code):
                    result.unparsed.append(str(p))
                    continue
                found = scan_node_source(code, path=p.name)
            except _TokeniserUnavailable:
                # The tokeniser is gone. This file was NOT examined, and saying so is the
                # entire point — an import failure that returned [] would publish a clean
                # exam over a file nobody read.
                result.unparsed.append(str(p))
                continue
            parsed += 1
            result.languages[LANG_NODE] += 1
            result.findings.extend(found)
            continue
        try:
            ast.parse(code)
        except (SyntaxError, ValueError):
            result.unparsed.append(str(p))
            continue
        parsed += 1
        result.languages[LANG_PYTHON] += 1
        result.findings.extend(scan_source(code, path=p.name))
    result.measured = parsed > 0
    return result


